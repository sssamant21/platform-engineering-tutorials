import copy,json,unittest
from pathlib import Path
from gcp_gate import validate
ROOT=Path(__file__).parent
SAFE=json.loads((ROOT/"fixtures/gcp-safe.json").read_text())
UNSAFE=json.loads((ROOT/"fixtures/gcp-unsafe.json").read_text())
PLAN=json.loads((ROOT/"fixtures/plan-safe.json").read_text())
DESTRUCTIVE=json.loads((ROOT/"fixtures/plan-destructive.json").read_text())
POLICY=json.loads((ROOT/"gcp-policy.json").read_text())
class GcpGateTests(unittest.TestCase):
    def bad(self,fn):
        m=copy.deepcopy(SAFE);fn(m);self.assertTrue(validate(m,PLAN,POLICY))
    def bad_plan(self,fn):
        p=copy.deepcopy(PLAN);fn(p);self.assertTrue(validate(SAFE,p,POLICY))
    def test_safe(self):self.assertEqual(validate(SAFE,PLAN,POLICY),[])
    def test_unsafe(self):self.assertTrue(validate(UNSAFE,DESTRUCTIVE,POLICY))
    def test_destructive(self):self.assertTrue(validate(SAFE,DESTRUCTIVE,POLICY))
    def test_environment(self):self.bad(lambda m:m.update(environment='invalid'))
    def test_project_id(self):self.bad(lambda m:m.update(project_id='INVALID'))
    def test_project_number(self):self.bad(lambda m:m.update(project_number='invalid'))
    def test_region(self):self.bad(lambda m:m.update(region='europe-west1'))
    def test_owner(self):self.bad(lambda m:m.update(owner=''))
    def test_ticket(self):self.bad(lambda m:m.update(change_ticket=''))
    def test_state_namespace(self):self.bad(lambda m:m.update(state_namespace='iac-dev'))
    def test_project_billing_reviewed(self):self.bad(lambda m:m['project'].update(billing_reviewed=False))
    def test_project_org_policy_reviewed(self):self.bad(lambda m:m['project'].update(org_policy_reviewed=False))
    def test_project_service_apis_reviewed(self):self.bad(lambda m:m['project'].update(service_apis_reviewed=False))
    def test_project_quota_reviewed(self):self.bad(lambda m:m['project'].update(quota_reviewed=False))
    def test_project_api_enablement_approved(self):self.bad(lambda m:m['project'].update(api_enablement_approved=False))
    def test_project_environment_isolated(self):self.bad(lambda m:m['project'].update(environment_isolated=False))
    def test_no_project(self):self.bad(lambda m:m.pop('project'))
    def test_identity_wif_enabled(self):self.bad(lambda m:m['identity'].update(wif_enabled=False))
    def test_identity_least_privilege_reviewed(self):self.bad(lambda m:m['identity'].update(least_privilege_reviewed=False))
    def test_identity_service_account_impersonation_reviewed(self):self.bad(lambda m:m['identity'].update(service_account_impersonation_reviewed=False))
    def test_no_identity(self):self.bad(lambda m:m.pop('identity'))
    def test_state_private(self):self.bad(lambda m:m['state'].update(private=False))
    def test_state_uniform_bucket_access(self):self.bad(lambda m:m['state'].update(uniform_bucket_access=False))
    def test_state_public_access_prevention(self):self.bad(lambda m:m['state'].update(public_access_prevention=False))
    def test_state_versioning(self):self.bad(lambda m:m['state'].update(versioning=False))
    def test_state_encrypted(self):self.bad(lambda m:m['state'].update(encrypted=False))
    def test_state_locking(self):self.bad(lambda m:m['state'].update(locking=False))
    def test_state_environment_isolated(self):self.bad(lambda m:m['state'].update(environment_isolated=False))
    def test_no_state(self):self.bad(lambda m:m.pop('state'))
    def test_audit_cloud_audit_logs_enabled(self):self.bad(lambda m:m['audit'].update(cloud_audit_logs_enabled=False))
    def test_audit_monitoring_enabled(self):self.bad(lambda m:m['audit'].update(monitoring_enabled=False))
    def test_audit_budget_alerts_enabled(self):self.bad(lambda m:m['audit'].update(budget_alerts_enabled=False))
    def test_audit_security_approved(self):self.bad(lambda m:m['audit'].update(security_approved=False))
    def test_audit_dbre_approved(self):self.bad(lambda m:m['audit'].update(dbre_approved=False))
    def test_no_audit(self):self.bad(lambda m:m.pop('audit'))
    def test_static_key(self):self.bad(lambda m:m['identity'].update(static_service_account_key_used=True))
    def test_oidc_issuer(self):self.bad(lambda m:m['identity'].update(oidc_issuer='https://evil.example'))
    def test_oidc_audience(self):self.bad(lambda m:m['identity'].update(oidc_audience='wrong'))
    def test_oidc_subject(self):self.bad(lambda m:m['identity'].update(oidc_subject='repo:*'))
    def test_environment_label(self):self.bad(lambda m:m['labels'].update(environment='dev'))
    def test_owner_label(self):self.bad(lambda m:m['labels'].update(owner=''))
    def test_managedby_label(self):self.bad(lambda m:m['labels'].update(**{'managed-by':'manual'}))
    def test_no_labels(self):self.bad(lambda m:m.pop('labels'))
    def test_delete(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["delete"]))
    def test_replace(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["create","delete"]))
    def test_invalid_action(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["destroy"]))
    def test_unapproved_type(self):self.bad_plan(lambda p:p["resource_changes"][0].update(type="google_project"))
    def test_missing_plan(self):self.assertTrue(validate(SAFE,{},POLICY))
    def test_invalid_manifest(self):self.assertTrue(validate([],PLAN,POLICY))
    def test_fail_open_policy(self):
        p=copy.deepcopy(POLICY);p["deny_destructive_actions"]=False;self.assertTrue(validate(SAFE,PLAN,p))
    def test_noop_allowed(self):
        p=copy.deepcopy(PLAN);p["resource_changes"][0]["change"]["actions"]=["no-op"];self.assertEqual(validate(SAFE,p,POLICY),[])
if __name__=="__main__":unittest.main()
