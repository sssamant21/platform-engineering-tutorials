import copy,json,unittest
from pathlib import Path
from acceptance_gate import validate
ROOT=Path(__file__).parent
SAFE=json.loads((ROOT/"fixtures/acceptance-safe.json").read_text())
UNSAFE=json.loads((ROOT/"fixtures/acceptance-unsafe.json").read_text())
PLAN=json.loads((ROOT/"fixtures/plan-safe.json").read_text())
DESTRUCTIVE=json.loads((ROOT/"fixtures/plan-destructive.json").read_text())
POLICY=json.loads((ROOT/"policy/acceptance-policy.json").read_text())
class CapstoneTests(unittest.TestCase):
    def bad(self,fn):
        m=copy.deepcopy(SAFE);fn(m);self.assertTrue(validate(m,PLAN,POLICY))
    def bad_plan(self,fn):
        p=copy.deepcopy(PLAN);fn(p);self.assertTrue(validate(SAFE,p,POLICY))
    def test_safe(self): self.assertEqual(validate(SAFE,PLAN,POLICY),[])
    def test_unsafe(self): self.assertTrue(validate(UNSAFE,DESTRUCTIVE,POLICY))
    def test_destructive(self): self.assertTrue(validate(SAFE,DESTRUCTIVE,POLICY))
    def test_ticket(self): self.bad(lambda m:m.update(change_ticket=""))
    def test_environment(self): self.bad(lambda m:m.update(environment="invalid"))
    def test_same_backend(self): self.bad(lambda m:m.update(dr_backend=m["source_backend"]))
    def test_no_source(self): self.bad(lambda m:m.update(source_backend=""))
    def test_no_dr(self): self.bad(lambda m:m.update(dr_backend=""))
    def test_bad_lineage(self): self.bad(lambda m:m.update(lineage="wrong"))
    def test_mismatched_lineage(self): self.bad(lambda m:m.update(snapshot_lineage="wrong"))
    def test_bad_serial(self): self.bad(lambda m:m.update(serial=-1))
    def test_bool_serial(self): self.bad(lambda m:m.update(serial=True))
    def test_mismatched_serial(self): self.bad(lambda m:m.update(snapshot_serial=13))
    def test_bad_digest(self): self.bad(lambda m:m.update(snapshot_sha256="no"))
    def test_retention(self): self.bad(lambda m:m.update(retention_days=1))
    def test_rpo(self): self.bad(lambda m:m.update(rpo_minutes=61))
    def test_rto(self): self.bad(lambda m:m.update(rto_minutes=241))
    def test_zero_rpo(self): self.bad(lambda m:m.update(rpo_minutes=0))
    def test_no_addresses(self): self.bad(lambda m:m.update(resource_addresses=[]))
    def test_duplicate_address(self): self.bad(lambda m:m["resource_addresses"].append("terraform_data.database"))
    def test_invalid_address(self): self.bad(lambda m:m.update(resource_addresses=[None]))
    def test_missing_controls(self): self.bad(lambda m:m.pop("controls"))
    def test_no_backup(self): self.bad(lambda m:m["controls"].update(state_backup_verified=False))
    def test_no_lock(self): self.bad(lambda m:m["controls"].update(exclusive_lock_verified=False))
    def test_no_freeze(self): self.bad(lambda m:m["controls"].update(writers_frozen=False))
    def test_no_encryption(self): self.bad(lambda m:m["controls"].update(encryption_verified=False))
    def test_no_versioning(self): self.bad(lambda m:m["controls"].update(versioning_verified=False))
    def test_no_audit(self): self.bad(lambda m:m["controls"].update(audit_verified=False))
    def test_no_restore(self): self.bad(lambda m:m["controls"].update(restore_tested=False))
    def test_no_identity(self): self.bad(lambda m:m["controls"].update(identity_scoped=False))
    def test_no_health(self): self.bad(lambda m:m["controls"].update(application_health_verified=False))
    def test_delete(self): self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["delete"]))
    def test_reverse_replace(self): self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["create","delete"]))
    def test_invalid_actions(self): self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["destroy"]))
    def test_unapproved_type(self): self.bad_plan(lambda p:p["resource_changes"][0].update(type="aws_db_instance"))
    def test_missing_plan(self): self.assertTrue(validate(SAFE,{},POLICY))
    def test_bad_manifest(self): self.assertTrue(validate([],PLAN,POLICY))
    def test_fail_open_policy(self):
        p=copy.deepcopy(POLICY);p["deny_destructive_actions"]=False;self.assertTrue(validate(SAFE,PLAN,p))
    def test_noop_allowed(self):
        p=copy.deepcopy(PLAN);p["resource_changes"][0]["change"]["actions"]=["no-op"];self.assertEqual(validate(SAFE,p,POLICY),[])
if __name__=="__main__":unittest.main()
