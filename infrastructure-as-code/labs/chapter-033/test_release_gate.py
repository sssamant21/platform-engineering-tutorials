import copy,json,unittest
from pathlib import Path
from release_gate import validate
ROOT=Path(__file__).parent
SAFE=json.loads((ROOT/"fixtures/release-safe.json").read_text())
UNSAFE=json.loads((ROOT/"fixtures/release-unsafe.json").read_text())
PLAN=json.loads((ROOT/"fixtures/plan-safe.json").read_text())
DESTRUCTIVE=json.loads((ROOT/"fixtures/plan-destructive.json").read_text())
POLICY=json.loads((ROOT/"version-policy.json").read_text())
class ReleaseGateTests(unittest.TestCase):
    def bad(self,fn):
        m=copy.deepcopy(SAFE);fn(m);self.assertTrue(validate(m,PLAN,POLICY))
    def bad_plan(self,fn):
        p=copy.deepcopy(PLAN);fn(p);self.assertTrue(validate(SAFE,p,POLICY))
    def test_safe(self):self.assertEqual(validate(SAFE,PLAN,POLICY),[])
    def test_unsafe(self):self.assertTrue(validate(UNSAFE,DESTRUCTIVE,POLICY))
    def test_destructive(self):self.assertTrue(validate(SAFE,DESTRUCTIVE,POLICY))
    def test_environment(self):self.bad(lambda m:m.update(environment="invalid"))
    def test_ticket(self):self.bad(lambda m:m.update(change_ticket=""))
    def test_owner(self):self.bad(lambda m:m.update(release_owner=""))
    def test_state_namespace(self):self.bad(lambda m:m.update(state_namespace="iac-dev"))
    def test_provenance(self):self.bad(lambda m:m.update(provenance_verified=False))
    def test_security_review(self):self.bad(lambda m:m.update(security_reviewed=False))
    def test_contract_tests(self):self.bad(lambda m:m.update(contract_tests_passed=False))
    def test_integration_tests(self):self.bad(lambda m:m.update(integration_tests_passed=False))
    def test_missing_modules(self):self.bad(lambda m:m.update(modules=[]))
    def test_missing_required_module(self):self.bad(lambda m:m["modules"].pop(0))
    def test_duplicate_name(self):self.bad(lambda m:m["modules"][1].update(name="network"))
    def test_unpinned_branch(self):self.bad(lambda m:m["modules"][0].update(source="git::https://github.com/example/x.git?ref=main"))
    def test_short_sha(self):self.bad(lambda m:m["modules"][0].update(source="git::https://github.com/example/x.git?ref=1234"))
    def test_unknown_git_host(self):self.bad(lambda m:m["modules"][0].update(source="git::https://evil.example/x.git?ref="+"a"*40))
    def test_local_source(self):self.bad(lambda m:m["modules"][0].update(source="./modules/network"))
    def test_unpinned_git(self):self.bad(lambda m:m["modules"][0].update(source="git::https://github.com/example/x.git"))
    def test_bad_version(self):self.bad(lambda m:m["modules"][0].update(version="latest"))
    def test_bad_semver(self):self.bad(lambda m:m["modules"][0].update(version="1.02.3"))
    def test_major_change(self):self.bad(lambda m:m["modules"][1].update(version="3.0.0"))
    def test_bool_major(self):self.bad(lambda m:m["modules"][1].update(approved_major=True))
    def test_module_owner(self):self.bad(lambda m:m["modules"][0].update(owner=""))
    def test_cycle(self):self.bad(lambda m:m["modules"][0].update(depends_on=["application"]))
    def test_unknown_dependency(self):self.bad(lambda m:m["modules"][0].update(depends_on=["missing"]))
    def test_database_dependency(self):self.bad(lambda m:m["modules"][1].update(depends_on=[]))
    def test_application_dependency(self):self.bad(lambda m:m["modules"][2].update(depends_on=[]))
    def test_prod_replicas(self):self.bad(lambda m:m["database"].update(replicas=1))
    def test_prod_backup(self):self.bad(lambda m:m["database"].update(backup_enabled=False))
    def test_prod_encryption(self):self.bad(lambda m:m["database"].update(encryption_enabled=False))
    def test_missing_database(self):self.bad(lambda m:m.pop("database"))
    def test_delete(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["delete"]))
    def test_reverse_replace(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["create","delete"]))
    def test_bad_action(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["destroy"]))
    def test_unapproved_resource(self):self.bad_plan(lambda p:p["resource_changes"][0].update(type="aws_db_instance"))
    def test_missing_plan(self):self.assertTrue(validate(SAFE,{},POLICY))
    def test_bad_manifest(self):self.assertTrue(validate([],PLAN,POLICY))
    def test_fail_open_policy(self):
        p=copy.deepcopy(POLICY);p["deny_destructive_actions"]=False;self.assertTrue(validate(SAFE,PLAN,p))
    def test_noop_allowed(self):
        p=copy.deepcopy(PLAN);p["resource_changes"][0]["change"]["actions"]=["no-op"];self.assertEqual(validate(SAFE,p,POLICY),[])
if __name__=="__main__":unittest.main()
