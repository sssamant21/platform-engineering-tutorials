import copy,json,unittest
from pathlib import Path
from stateful_gate import validate
ROOT=Path(__file__).parent
SAFE=json.loads((ROOT/"fixtures/stateful-safe.json").read_text())
UNSAFE=json.loads((ROOT/"fixtures/stateful-unsafe.json").read_text())
PLAN=json.loads((ROOT/"fixtures/plan-safe.json").read_text())
DESTRUCTIVE=json.loads((ROOT/"fixtures/plan-destructive.json").read_text())
POLICY=json.loads((ROOT/"stateful-policy.json").read_text())
class StatefulGateTests(unittest.TestCase):
    def bad(self,fn):
        m=copy.deepcopy(SAFE);fn(m);self.assertTrue(validate(m,PLAN,POLICY))
    def bad_plan(self,fn):
        p=copy.deepcopy(PLAN);fn(p);self.assertTrue(validate(SAFE,p,POLICY))
    def test_safe(self):self.assertEqual(validate(SAFE,PLAN,POLICY),[])
    def test_unsafe(self):self.assertTrue(validate(UNSAFE,DESTRUCTIVE,POLICY))
    def test_destructive(self):self.assertTrue(validate(SAFE,DESTRUCTIVE,POLICY))
    def test_environment(self):self.bad(lambda m:m.update(environment="invalid"))
    def test_account_short(self):self.bad(lambda m:m.update(aws_account_id="123"))
    def test_account_letters(self):self.bad(lambda m:m.update(aws_account_id="a"*12))
    def test_primary_region(self):self.bad(lambda m:m.update(primary_region="eu-west-1"))
    def test_dr_region(self):self.bad(lambda m:m.update(dr_region="eu-west-1"))
    def test_same_region(self):self.bad(lambda m:m.update(dr_region="us-east-1"))
    def test_owner(self):self.bad(lambda m:m.update(owner=""))
    def test_ticket(self):self.bad(lambda m:m.update(change_ticket=""))
    def test_state_namespace(self):self.bad(lambda m:m.update(state_namespace="iac-dev"))
    def test_database_engine(self):self.bad(lambda m:m["database"].update(engine="mysql"))
    def test_database_multi_az(self):self.bad(lambda m:m["database"].update(multi_az=False))
    def test_database_encryption(self):self.bad(lambda m:m["database"].update(encrypted=False))
    def test_database_deletion_protection(self):self.bad(lambda m:m["database"].update(deletion_protection=False))
    def test_database_pitr(self):self.bad(lambda m:m["database"].update(pitr_enabled=False))
    def test_database_private(self):self.bad(lambda m:m["database"].update(private_subnets=False))
    def test_database_restore(self):self.bad(lambda m:m["database"].update(backup_restore_tested=False))
    def test_database_retention_low(self):self.bad(lambda m:m["database"].update(backup_retention_days=1))
    def test_database_retention_high(self):self.bad(lambda m:m["database"].update(backup_retention_days=36))
    def test_database_retention_bool(self):self.bad(lambda m:m["database"].update(backup_retention_days=True))
    def test_no_database(self):self.bad(lambda m:m.pop("database"))
    def test_s3_versioning(self):self.bad(lambda m:m["s3"].update(versioning=False))
    def test_s3_encryption(self):self.bad(lambda m:m["s3"].update(encrypted=False))
    def test_s3_public(self):self.bad(lambda m:m["s3"].update(public_access_blocked=False))
    def test_s3_lifecycle(self):self.bad(lambda m:m["s3"].update(lifecycle_reviewed=False))
    def test_s3_restore(self):self.bad(lambda m:m["s3"].update(restore_tested=False))
    def test_no_s3(self):self.bad(lambda m:m.pop("s3"))
    def test_ebs_encryption(self):self.bad(lambda m:m["volumes"].update(ebs_encrypted=False))
    def test_efs_encryption(self):self.bad(lambda m:m["volumes"].update(efs_encrypted=False))
    def test_ebs_snapshot(self):self.bad(lambda m:m["volumes"].update(ebs_snapshot_tested=False))
    def test_efs_restore(self):self.bad(lambda m:m["volumes"].update(efs_restore_tested=False))
    def test_no_volumes(self):self.bad(lambda m:m.pop("volumes"))
    def test_rpo_high(self):self.bad(lambda m:m["recovery"].update(rpo_minutes=1441))
    def test_rpo_negative(self):self.bad(lambda m:m["recovery"].update(rpo_minutes=-1))
    def test_rto_zero(self):self.bad(lambda m:m["recovery"].update(rto_minutes=0))
    def test_rto_bool(self):self.bad(lambda m:m["recovery"].update(rto_minutes=True))
    def test_cross_region_backup(self):self.bad(lambda m:m["recovery"].update(cross_region_backup=False))
    def test_writer_fencing(self):self.bad(lambda m:m["recovery"].update(writer_fencing_tested=False))
    def test_kms_decrypt(self):self.bad(lambda m:m["recovery"].update(kms_decrypt_tested=False))
    def test_dr_drill(self):self.bad(lambda m:m["recovery"].update(dr_drill_passed=False))
    def test_no_recovery(self):self.bad(lambda m:m.pop("recovery"))
    def test_cloudwatch(self):self.bad(lambda m:m["audit"].update(cloudwatch_enabled=False))
    def test_cloudtrail(self):self.bad(lambda m:m["audit"].update(cloudtrail_enabled=False))
    def test_security_review(self):self.bad(lambda m:m["audit"].update(security_reviewed=False))
    def test_dbre_approval(self):self.bad(lambda m:m["audit"].update(dbre_approved=False))
    def test_no_audit(self):self.bad(lambda m:m.pop("audit"))
    def test_tag_environment(self):self.bad(lambda m:m["tags"].update(Environment="dev"))
    def test_tag_owner(self):self.bad(lambda m:m["tags"].update(Owner=""))
    def test_tag_managedby(self):self.bad(lambda m:m["tags"].update(ManagedBy="manual"))
    def test_no_tags(self):self.bad(lambda m:m.pop("tags"))
    def test_delete(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["delete"]))
    def test_replace(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["create","delete"]))
    def test_bad_action(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["destroy"]))
    def test_unapproved_type(self):self.bad_plan(lambda p:p["resource_changes"][0].update(type="aws_db_instance"))
    def test_missing_plan(self):self.assertTrue(validate(SAFE,{},POLICY))
    def test_bad_manifest(self):self.assertTrue(validate([],PLAN,POLICY))
    def test_fail_open_policy(self):
        p=copy.deepcopy(POLICY);p["deny_destructive_actions"]=False;self.assertTrue(validate(SAFE,PLAN,p))
    def test_noop_allowed(self):
        p=copy.deepcopy(PLAN);p["resource_changes"][0]["change"]["actions"]=["no-op"];self.assertEqual(validate(SAFE,p,POLICY),[])
if __name__=="__main__":unittest.main()
