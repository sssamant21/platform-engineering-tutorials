import copy,json,unittest
from pathlib import Path
from compatibility_gate import validate
ROOT=Path(__file__).parent
SAFE=json.loads((ROOT/"fixtures/compatibility-safe.json").read_text())
UNSAFE=json.loads((ROOT/"fixtures/compatibility-unsafe.json").read_text())
PLAN=json.loads((ROOT/"fixtures/plan-safe.json").read_text())
DESTRUCTIVE=json.loads((ROOT/"fixtures/plan-destructive.json").read_text())
POLICY=json.loads((ROOT/"compatibility-policy.json").read_text())
class CompatibilityGateTests(unittest.TestCase):
    def bad(self,fn):
        m=copy.deepcopy(SAFE);fn(m);self.assertTrue(validate(m,PLAN,POLICY))
    def bad_plan(self,fn):
        p=copy.deepcopy(PLAN);fn(p);self.assertTrue(validate(SAFE,p,POLICY))
    def test_safe(self):self.assertEqual(validate(SAFE,PLAN,POLICY),[])
    def test_unsafe(self):self.assertTrue(validate(UNSAFE,DESTRUCTIVE,POLICY))
    def test_destructive(self):self.assertTrue(validate(SAFE,DESTRUCTIVE,POLICY))
    def test_environment(self):self.bad(lambda m:m.update(environment='invalid'))
    def test_root_name(self):self.bad(lambda m:m.update(root_name=''))
    def test_backend_key(self):self.bad(lambda m:m.update(backend_key='iac/dev/other'))
    def test_owner(self):self.bad(lambda m:m.update(owner=''))
    def test_ticket(self):self.bad(lambda m:m.update(change_ticket=''))
    def test_state_namespace(self):self.bad(lambda m:m.update(state_namespace='iac-dev'))
    def test_state_backend_isolated(self):self.bad(lambda m:m['state'].update(backend_isolated=False))
    def test_state_backend_encrypted(self):self.bad(lambda m:m['state'].update(backend_encrypted=False))
    def test_state_locking_verified(self):self.bad(lambda m:m['state'].update(locking_verified=False))
    def test_state_lineage_recorded(self):self.bad(lambda m:m['state'].update(lineage_recorded=False))
    def test_state_serial_recorded(self):self.bad(lambda m:m['state'].update(serial_recorded=False))
    def test_state_state_backup_verified(self):self.bad(lambda m:m['state'].update(state_backup_verified=False))
    def test_state_restore_tested(self):self.bad(lambda m:m['state'].update(restore_tested=False))
    def test_state_exclusive_writer(self):self.bad(lambda m:m['state'].update(exclusive_writer=False))
    def test_no_state(self):self.bad(lambda m:m.pop('state'))
    def test_provider_provider_source_pinned(self):self.bad(lambda m:m['provider'].update(provider_source_pinned=False))
    def test_provider_provider_version_pinned(self):self.bad(lambda m:m['provider'].update(provider_version_pinned=False))
    def test_provider_lockfile_reviewed(self):self.bad(lambda m:m['provider'].update(lockfile_reviewed=False))
    def test_provider_schema_compatibility_reviewed(self):self.bad(lambda m:m['provider'].update(schema_compatibility_reviewed=False))
    def test_provider_registry_trusted(self):self.bad(lambda m:m['provider'].update(registry_trusted=False))
    def test_provider_auth_short_lived(self):self.bad(lambda m:m['provider'].update(auth_short_lived=False))
    def test_no_provider(self):self.bad(lambda m:m.pop('provider'))
    def test_module_module_sources_pinned(self):self.bad(lambda m:m['module'].update(module_sources_pinned=False))
    def test_module_module_contract_tested(self):self.bad(lambda m:m['module'].update(module_contract_tested=False))
    def test_module_input_output_reviewed(self):self.bad(lambda m:m['module'].update(input_output_reviewed=False))
    def test_module_address_migrations_reviewed(self):self.bad(lambda m:m['module'].update(address_migrations_reviewed=False))
    def test_module_transitive_deps_reviewed(self):self.bad(lambda m:m['module'].update(transitive_deps_reviewed=False))
    def test_module_module_rollback_tested(self):self.bad(lambda m:m['module'].update(module_rollback_tested=False))
    def test_no_module(self):self.bad(lambda m:m.pop('module'))
    def test_operations_plan_policy_enabled(self):self.bad(lambda m:m['operations'].update(plan_policy_enabled=False))
    def test_operations_native_plan_adapter_reviewed(self):self.bad(lambda m:m['operations'].update(native_plan_adapter_reviewed=False))
    def test_operations_drift_reviewed(self):self.bad(lambda m:m['operations'].update(drift_reviewed=False))
    def test_operations_slo_monitored(self):self.bad(lambda m:m['operations'].update(slo_monitored=False))
    def test_operations_dbre_approved(self):self.bad(lambda m:m['operations'].update(dbre_approved=False))
    def test_operations_security_approved(self):self.bad(lambda m:m['operations'].update(security_approved=False))
    def test_operations_change_approved(self):self.bad(lambda m:m['operations'].update(change_approved=False))
    def test_no_operations(self):self.bad(lambda m:m.pop('operations'))
    def test_concurrent_writers(self):self.bad(lambda m:m['state'].update(concurrent_writers=True))
    def test_unexpected_replacement(self):self.bad(lambda m:m['provider'].update(unexpected_replacement=True))
    def test_unapproved_destroy(self):self.bad(lambda m:m['operations'].update(unapproved_destroy=True))
    def test_environment_label(self):self.bad(lambda m:m['labels'].update(environment='dev'))
    def test_owner_label(self):self.bad(lambda m:m['labels'].update(owner=''))
    def test_managedby_label(self):self.bad(lambda m:m['labels'].update(**{'managed-by':'manual'}))
    def test_no_labels(self):self.bad(lambda m:m.pop('labels'))
    def test_delete(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["delete"]))
    def test_replace(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["create","delete"]))
    def test_invalid_action(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["destroy"]))
    def test_unapproved_type(self):self.bad_plan(lambda p:p["resource_changes"][0].update(type="aws_db_instance"))
    def test_missing_plan(self):self.assertTrue(validate(SAFE,{},POLICY))
    def test_invalid_manifest(self):self.assertTrue(validate([],PLAN,POLICY))
    def test_fail_open_policy(self):
        p=copy.deepcopy(POLICY);p["deny_destructive_actions"]=False;self.assertTrue(validate(SAFE,PLAN,p))
    def test_noop_allowed(self):
        p=copy.deepcopy(PLAN);p["resource_changes"][0]["change"]["actions"]=["no-op"];self.assertEqual(validate(SAFE,p,POLICY),[])
if __name__=="__main__":unittest.main()
