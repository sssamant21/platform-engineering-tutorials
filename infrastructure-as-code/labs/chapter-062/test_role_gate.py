import copy,json,unittest
from pathlib import Path
from role_gate import validate
ROOT=Path(__file__).parent
SAFE=json.loads((ROOT/"fixtures/safe.json").read_text())
UNSAFE=json.loads((ROOT/"fixtures/unsafe.json").read_text())
POLICY=json.loads((ROOT/"policy.json").read_text())
class RoleGateTests(unittest.TestCase):
    def bad(self,fn):
        m=copy.deepcopy(SAFE);fn(m);self.assertTrue(validate(m,POLICY))
    def test_safe(self):self.assertEqual(validate(SAFE,POLICY),[])
    def test_unsafe(self):self.assertTrue(validate(UNSAFE,POLICY))
    def test_env(self):self.bad(lambda m:m.update(environment='prod'))
    def test_inventory(self):self.bad(lambda m:m.update(inventory='prod.ini'))
    def test_targets(self):self.bad(lambda m:m.update(target_hosts=['db-prod-01']))
    def test_owner(self):self.bad(lambda m:m.update(owner=''))
    def test_ticket(self):self.bad(lambda m:m.update(change_ticket=''))
    def test_labels(self):self.bad(lambda m:m.pop('labels'))
    def test_label_env(self):self.bad(lambda m:m['labels'].update(environment='prod'))
    def test_label_owner(self):self.bad(lambda m:m['labels'].update(owner='other'))
    def test_label_manager(self):self.bad(lambda m:m['labels'].update(**{'managed-by':'manual'}))
    def test_inventory_localhost_only(self):self.bad(lambda m:m['inventory'].update(localhost_only=False))
    def test_inventory_hosts_reviewed(self):self.bad(lambda m:m['inventory'].update(hosts_reviewed=False))
    def test_inventory_inventory_isolated(self):self.bad(lambda m:m['inventory'].update(inventory_isolated=False))
    def test_inventory_limit_verified(self):self.bad(lambda m:m['inventory'].update(limit_verified=False))
    def test_inventory_owner_defined(self):self.bad(lambda m:m['inventory'].update(owner_defined=False))
    def test_missing_inventory(self):self.bad(lambda m:m.pop('inventory'))
    def test_roles_role_reusable(self):self.bad(lambda m:m['roles'].update(role_reusable=False))
    def test_roles_defaults_defined(self):self.bad(lambda m:m['roles'].update(defaults_defined=False))
    def test_roles_tasks_fqcn(self):self.bad(lambda m:m['roles'].update(tasks_fqcn=False))
    def test_roles_templates_reviewed(self):self.bad(lambda m:m['roles'].update(templates_reviewed=False))
    def test_roles_handlers_change_only(self):self.bad(lambda m:m['roles'].update(handlers_change_only=False))
    def test_roles_variable_contracts_validated(self):self.bad(lambda m:m['roles'].update(variable_contracts_validated=False))
    def test_roles_idempotence_verified(self):self.bad(lambda m:m['roles'].update(idempotence_verified=False))
    def test_missing_roles(self):self.bad(lambda m:m.pop('roles'))
    def test_security_least_privilege(self):self.bad(lambda m:m['security'].update(least_privilege=False))
    def test_security_become_disabled(self):self.bad(lambda m:m['security'].update(become_disabled=False))
    def test_security_secrets_external(self):self.bad(lambda m:m['security'].update(secrets_external=False))
    def test_security_diff_safe(self):self.bad(lambda m:m['security'].update(diff_safe=False))
    def test_security_dependencies_pinned(self):self.bad(lambda m:m['security'].update(dependencies_pinned=False))
    def test_security_change_approved(self):self.bad(lambda m:m['security'].update(change_approved=False))
    def test_missing_security(self):self.bad(lambda m:m.pop('security'))
    def test_operations_check_mode_reviewed(self):self.bad(lambda m:m['operations'].update(check_mode_reviewed=False))
    def test_operations_drift_tested(self):self.bad(lambda m:m['operations'].update(drift_tested=False))
    def test_operations_backup_verified(self):self.bad(lambda m:m['operations'].update(backup_verified=False))
    def test_operations_dbre_approved(self):self.bad(lambda m:m['operations'].update(dbre_approved=False))
    def test_operations_rollback_documented(self):self.bad(lambda m:m['operations'].update(rollback_documented=False))
    def test_operations_slo_reviewed(self):self.bad(lambda m:m['operations'].update(slo_reviewed=False))
    def test_missing_operations(self):self.bad(lambda m:m.pop('operations'))
    def test_restart(self):self.bad(lambda m:m['operations'].update(unapproved_restart=True))
    def test_secrets(self):self.bad(lambda m:m['security'].update(plaintext_secrets=True))
    def test_bad_manifest(self):self.assertTrue(validate([],POLICY))
    def test_bad_policy(self):self.assertTrue(validate(SAFE,[]))
    def test_fail_open(self):
        p=copy.deepcopy(POLICY);p["deny_prod_targets"]=False;self.assertTrue(validate(SAFE,p))
    def test_missing_controls(self):
        p=copy.deepcopy(POLICY);p.pop("required_controls");self.assertTrue(validate(SAFE,p))
if __name__=="__main__":unittest.main()
