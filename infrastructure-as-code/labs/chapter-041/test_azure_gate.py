import copy,json,unittest
from pathlib import Path
from azure_gate import validate
ROOT=Path(__file__).parent
SAFE=json.loads((ROOT/"fixtures/azure-safe.json").read_text())
UNSAFE=json.loads((ROOT/"fixtures/azure-unsafe.json").read_text())
PLAN=json.loads((ROOT/"fixtures/plan-safe.json").read_text())
DESTRUCTIVE=json.loads((ROOT/"fixtures/plan-destructive.json").read_text())
POLICY=json.loads((ROOT/"azure-policy.json").read_text())
class AzureGateTests(unittest.TestCase):
    def bad(self,fn):
        m=copy.deepcopy(SAFE);fn(m);self.assertTrue(validate(m,PLAN,POLICY))
    def bad_plan(self,fn):
        p=copy.deepcopy(PLAN);fn(p);self.assertTrue(validate(SAFE,p,POLICY))
    def test_safe(self):self.assertEqual(validate(SAFE,PLAN,POLICY),[])
    def test_unsafe(self):self.assertTrue(validate(UNSAFE,DESTRUCTIVE,POLICY))
    def test_destructive(self):self.assertTrue(validate(SAFE,DESTRUCTIVE,POLICY))
    def test_environment(self):self.bad(lambda m:m.update(environment="unknown"))
    def test_tenant_id(self):self.bad(lambda m:m.update(tenant_id="invalid"))
    def test_subscription_id(self):self.bad(lambda m:m.update(subscription_id="invalid"))
    def test_location(self):self.bad(lambda m:m.update(location="westeurope"))
    def test_owner(self):self.bad(lambda m:m.update(owner=""))
    def test_ticket(self):self.bad(lambda m:m.update(change_ticket=""))
    def test_state_namespace(self):self.bad(lambda m:m.update(state_namespace="iac-dev"))
    def test_oidc_disabled(self):self.bad(lambda m:m["identity"].update(oidc_federation_enabled=False))
    def test_static_secret(self):self.bad(lambda m:m["identity"].update(static_client_secret_used=True))
    def test_oidc_issuer(self):self.bad(lambda m:m["identity"].update(oidc_issuer="https://evil.example"))
    def test_oidc_audience(self):self.bad(lambda m:m["identity"].update(oidc_audience="other"))
    def test_oidc_wildcard(self):self.bad(lambda m:m["identity"].update(oidc_subject="repo:*"))
    def test_oidc_wrong_environment(self):self.bad(lambda m:m["identity"].update(oidc_subject="repo:example-org/platform-infra:environment:dev"))
    def test_oidc_branch(self):self.bad(lambda m:m["identity"].update(oidc_subject="repo:example-org/platform-infra:ref:refs/heads/main"))
    def test_least_privilege(self):self.bad(lambda m:m["identity"].update(least_privilege_reviewed=False))
    def test_role_assignment_wildcard(self):self.bad(lambda m:m["identity"].update(role_assignment_wildcard=True))
    def test_no_identity(self):self.bad(lambda m:m.pop("identity"))
    def test_azure_policy(self):self.bad(lambda m:m["governance"].update(azure_policy_enabled=False))
    def test_rbac_scope(self):self.bad(lambda m:m["governance"].update(rbac_scoped=False))
    def test_provider_registration(self):self.bad(lambda m:m["governance"].update(resource_providers_reviewed=False))
    def test_location_policy(self):self.bad(lambda m:m["governance"].update(allowed_locations_enforced=False))
    def test_no_governance(self):self.bad(lambda m:m.pop("governance"))
    def test_state_encryption(self):self.bad(lambda m:m["state"].update(encrypted=False))
    def test_state_network(self):self.bad(lambda m:m["state"].update(private_endpoint_or_restricted_network=False))
    def test_state_azuread(self):self.bad(lambda m:m["state"].update(azuread_auth=False))
    def test_state_locking(self):self.bad(lambda m:m["state"].update(locking_enabled=False))
    def test_state_versioning(self):self.bad(lambda m:m["state"].update(versioning_enabled=False))
    def test_state_recovery(self):self.bad(lambda m:m["state"].update(backup_recovery_tested=False))
    def test_no_state(self):self.bad(lambda m:m.pop("state"))
    def test_key_vault_private(self):self.bad(lambda m:m["security"].update(key_vault_private=False))
    def test_managed_identity(self):self.bad(lambda m:m["security"].update(managed_identity_enabled=False))
    def test_activity_logs(self):self.bad(lambda m:m["security"].update(activity_logs_enabled=False))
    def test_defender_review(self):self.bad(lambda m:m["security"].update(defender_reviewed=False))
    def test_no_security(self):self.bad(lambda m:m.pop("security"))
    def test_environment_tag(self):self.bad(lambda m:m["tags"].update(Environment="dev"))
    def test_owner_tag(self):self.bad(lambda m:m["tags"].update(Owner=""))
    def test_managedby_tag(self):self.bad(lambda m:m["tags"].update(ManagedBy="manual"))
    def test_no_tags(self):self.bad(lambda m:m.pop("tags"))
    def test_delete(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["delete"]))
    def test_replace(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["create","delete"]))
    def test_invalid_action(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["destroy"]))
    def test_unapproved_type(self):self.bad_plan(lambda p:p["resource_changes"][0].update(type="azurerm_resource_group"))
    def test_missing_plan(self):self.assertTrue(validate(SAFE,{},POLICY))
    def test_invalid_manifest(self):self.assertTrue(validate([],PLAN,POLICY))
    def test_fail_open_policy(self):
        p=copy.deepcopy(POLICY);p["deny_destructive_actions"]=False;self.assertTrue(validate(SAFE,PLAN,p))
    def test_noop_allowed(self):
        p=copy.deepcopy(PLAN);p["resource_changes"][0]["change"]["actions"]=["no-op"];self.assertEqual(validate(SAFE,p,POLICY),[])
if __name__=="__main__":unittest.main()
