import copy,json,unittest
from pathlib import Path
from compute_gate import validate
ROOT=Path(__file__).parent
SAFE=json.loads((ROOT/"fixtures/compute-safe.json").read_text())
UNSAFE=json.loads((ROOT/"fixtures/compute-unsafe.json").read_text())
PLAN=json.loads((ROOT/"fixtures/plan-safe.json").read_text())
DESTRUCTIVE=json.loads((ROOT/"fixtures/plan-destructive.json").read_text())
POLICY=json.loads((ROOT/"compute-policy.json").read_text())
class ComputeGateTests(unittest.TestCase):
    def bad(self,fn):
        m=copy.deepcopy(SAFE);fn(m);self.assertTrue(validate(m,PLAN,POLICY))
    def bad_plan(self,fn):
        p=copy.deepcopy(PLAN);fn(p);self.assertTrue(validate(SAFE,p,POLICY))
    def test_safe(self):self.assertEqual(validate(SAFE,PLAN,POLICY),[])
    def test_unsafe(self):self.assertTrue(validate(UNSAFE,DESTRUCTIVE,POLICY))
    def test_destructive(self):self.assertTrue(validate(SAFE,DESTRUCTIVE,POLICY))
    def test_environment(self):self.bad(lambda m:m.update(environment="unknown"))
    def test_account(self):self.bad(lambda m:m.update(aws_account_id="123"))
    def test_account_letters(self):self.bad(lambda m:m.update(aws_account_id="a"*12))
    def test_region(self):self.bad(lambda m:m.update(region="eu-west-1"))
    def test_owner(self):self.bad(lambda m:m.update(owner=""))
    def test_ticket(self):self.bad(lambda m:m.update(change_ticket=""))
    def test_state_namespace(self):self.bad(lambda m:m.update(state_namespace="iac-dev"))
    def test_single_az(self):self.bad(lambda m:m.update(availability_zones=["us-east-1a"]))
    def test_duplicate_az(self):self.bad(lambda m:m.update(availability_zones=["us-east-1a","us-east-1a"]))
    def test_public_instances(self):self.bad(lambda m:m["compute"].update(private_instances=False))
    def test_imdsv2(self):self.bad(lambda m:m["compute"].update(imds_v2_required=False))
    def test_ebs_encryption(self):self.bad(lambda m:m["compute"].update(ebs_encrypted=False))
    def test_immutable_ami(self):self.bad(lambda m:m["compute"].update(immutable_ami=False))
    def test_instance_profile(self):self.bad(lambda m:m["compute"].update(instance_profile_scoped=False))
    def test_asg_min(self):self.bad(lambda m:m["compute"].update(asg_min=1))
    def test_asg_order(self):self.bad(lambda m:m["compute"].update(asg_desired=7))
    def test_asg_bool(self):self.bad(lambda m:m["compute"].update(asg_max=True))
    def test_no_compute(self):self.bad(lambda m:m.pop("compute"))
    def test_alb_https(self):self.bad(lambda m:m["alb"].update(https_enabled=False))
    def test_alb_sg(self):self.bad(lambda m:m["alb"].update(security_group_reviewed=False))
    def test_alb_path(self):self.bad(lambda m:m["alb"].update(readiness_path="/"))
    def test_alb_threshold(self):self.bad(lambda m:m["alb"].update(healthy_target_threshold=1))
    def test_no_alb(self):self.bad(lambda m:m.pop("alb"))
    def test_eks_private_endpoint(self):self.bad(lambda m:m["eks"].update(private_endpoint=False))
    def test_eks_logging(self):self.bad(lambda m:m["eks"].update(control_plane_logging=False))
    def test_eks_encryption(self):self.bad(lambda m:m["eks"].update(secrets_encrypted=False))
    def test_eks_managed_nodes(self):self.bad(lambda m:m["eks"].update(managed_node_groups=False))
    def test_eks_pod_identity(self):self.bad(lambda m:m["eks"].update(pod_identity_scoped=False))
    def test_eks_addons(self):self.bad(lambda m:m["eks"].update(addon_compatibility_reviewed=False))
    def test_eks_min_nodes(self):self.bad(lambda m:m["eks"].update(node_min=1))
    def test_eks_node_order(self):self.bad(lambda m:m["eks"].update(node_desired=7))
    def test_eks_node_bool(self):self.bad(lambda m:m["eks"].update(node_max=True))
    def test_no_eks(self):self.bad(lambda m:m.pop("eks"))
    def test_cloudwatch(self):self.bad(lambda m:m["audit"].update(cloudwatch_enabled=False))
    def test_security_review(self):self.bad(lambda m:m["audit"].update(security_reviewed=False))
    def test_slo(self):self.bad(lambda m:m["audit"].update(slo_defined=False))
    def test_no_audit(self):self.bad(lambda m:m.pop("audit"))
    def test_tag_environment(self):self.bad(lambda m:m["tags"].update(Environment="dev"))
    def test_tag_owner(self):self.bad(lambda m:m["tags"].update(Owner=""))
    def test_tag_managedby(self):self.bad(lambda m:m["tags"].update(ManagedBy="manual"))
    def test_no_tags(self):self.bad(lambda m:m.pop("tags"))
    def test_delete(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["delete"]))
    def test_replace(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["delete","create"]))
    def test_invalid_action(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["destroy"]))
    def test_resource_type(self):self.bad_plan(lambda p:p["resource_changes"][0].update(type="aws_eks_cluster"))
    def test_missing_plan(self):self.assertTrue(validate(SAFE,{},POLICY))
    def test_invalid_manifest(self):self.assertTrue(validate([],PLAN,POLICY))
    def test_fail_open_policy(self):
        p=copy.deepcopy(POLICY);p["deny_destructive_actions"]=False;self.assertTrue(validate(SAFE,PLAN,p))
    def test_noop_allowed(self):
        p=copy.deepcopy(PLAN);p["resource_changes"][0]["change"]["actions"]=["no-op"];self.assertEqual(validate(SAFE,p,POLICY),[])
if __name__=="__main__":unittest.main()
