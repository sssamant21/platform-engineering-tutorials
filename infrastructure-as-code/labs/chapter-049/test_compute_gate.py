import copy,json,unittest
from pathlib import Path
from compute_gate import validate
ROOT=Path(__file__).parent
SAFE=json.loads((ROOT/"fixtures/compute-safe.json").read_text())
UNSAFE=json.loads((ROOT/"fixtures/compute-unsafe.json").read_text())
PLAN=json.loads((ROOT/"fixtures/plan-safe.json").read_text())
DESTRUCTIVE=json.loads((ROOT/"fixtures/plan-destructive.json").read_text())
POLICY=json.loads((ROOT/"compute-policy.json").read_text())
class ComputeGateTests(unittest.TestCase):
    def bad(self,fn):
        m=copy.deepcopy(SAFE);fn(m);self.assertTrue(validate(m,PLAN,POLICY))
    def bad_plan(self,fn):
        p=copy.deepcopy(PLAN);fn(p);self.assertTrue(validate(SAFE,p,POLICY))
    def test_safe(self):self.assertEqual(validate(SAFE,PLAN,POLICY),[])
    def test_unsafe(self):self.assertTrue(validate(UNSAFE,DESTRUCTIVE,POLICY))
    def test_destructive(self):self.assertTrue(validate(SAFE,DESTRUCTIVE,POLICY))
    def test_environment(self):self.bad(lambda m:m.update(environment='invalid'))
    def test_project_id(self):self.bad(lambda m:m.update(project_id='INVALID'))
    def test_project_number(self):self.bad(lambda m:m.update(project_number='invalid'))
    def test_region(self):self.bad(lambda m:m.update(region='europe-west1'))
    def test_owner(self):self.bad(lambda m:m.update(owner=''))
    def test_ticket(self):self.bad(lambda m:m.update(change_ticket=''))
    def test_state_namespace(self):self.bad(lambda m:m.update(state_namespace='iac-dev'))
    def test_compute_mig_regional(self):self.bad(lambda m:m['compute'].update(mig_regional=False))
    def test_compute_mig_autohealing(self):self.bad(lambda m:m['compute'].update(mig_autohealing=False))
    def test_compute_mig_autoscaling(self):self.bad(lambda m:m['compute'].update(mig_autoscaling=False))
    def test_compute_vm_shielded(self):self.bad(lambda m:m['compute'].update(vm_shielded=False))
    def test_compute_vm_os_login(self):self.bad(lambda m:m['compute'].update(vm_os_login=False))
    def test_compute_quota_reviewed(self):self.bad(lambda m:m['compute'].update(quota_reviewed=False))
    def test_no_compute(self):self.bad(lambda m:m.pop('compute'))
    def test_gke_private_nodes(self):self.bad(lambda m:m['gke'].update(private_nodes=False))
    def test_gke_private_endpoint_reviewed(self):self.bad(lambda m:m['gke'].update(private_endpoint_reviewed=False))
    def test_gke_workload_identity(self):self.bad(lambda m:m['gke'].update(workload_identity=False))
    def test_gke_network_policy(self):self.bad(lambda m:m['gke'].update(network_policy=False))
    def test_gke_release_channel_reviewed(self):self.bad(lambda m:m['gke'].update(release_channel_reviewed=False))
    def test_gke_pdb_reviewed(self):self.bad(lambda m:m['gke'].update(pdb_reviewed=False))
    def test_gke_autoscaling_reviewed(self):self.bad(lambda m:m['gke'].update(autoscaling_reviewed=False))
    def test_gke_secondary_ranges_reviewed(self):self.bad(lambda m:m['gke'].update(secondary_ranges_reviewed=False))
    def test_no_gke(self):self.bad(lambda m:m.pop('gke'))
    def test_application_ingress_tls(self):self.bad(lambda m:m['application'].update(ingress_tls=False))
    def test_application_health_checks(self):self.bad(lambda m:m['application'].update(health_checks=False))
    def test_application_image_digest_pinned(self):self.bad(lambda m:m['application'].update(image_digest_pinned=False))
    def test_application_image_provenance_reviewed(self):self.bad(lambda m:m['application'].update(image_provenance_reviewed=False))
    def test_application_db_private_connectivity_reviewed(self):self.bad(lambda m:m['application'].update(db_private_connectivity_reviewed=False))
    def test_application_db_connection_pooling_reviewed(self):self.bad(lambda m:m['application'].update(db_connection_pooling_reviewed=False))
    def test_no_application(self):self.bad(lambda m:m.pop('application'))
    def test_operations_monitoring_enabled(self):self.bad(lambda m:m['operations'].update(monitoring_enabled=False))
    def test_operations_audit_logs_enabled(self):self.bad(lambda m:m['operations'].update(audit_logs_enabled=False))
    def test_operations_rollback_tested(self):self.bad(lambda m:m['operations'].update(rollback_tested=False))
    def test_operations_dbre_approved(self):self.bad(lambda m:m['operations'].update(dbre_approved=False))
    def test_operations_security_approved(self):self.bad(lambda m:m['operations'].update(security_approved=False))
    def test_operations_change_approved(self):self.bad(lambda m:m['operations'].update(change_approved=False))
    def test_no_operations(self):self.bad(lambda m:m.pop('operations'))
    def test_public_vm(self):self.bad(lambda m:m['compute'].update(vm_public_ip=True))
    def test_static_key(self):self.bad(lambda m:m['gke'].update(static_service_account_keys=True))
    def test_secret_in_state(self):self.bad(lambda m:m['application'].update(secret_payload_in_state=True))
    def test_environment_label(self):self.bad(lambda m:m['labels'].update(environment='dev'))
    def test_owner_label(self):self.bad(lambda m:m['labels'].update(owner=''))
    def test_managedby_label(self):self.bad(lambda m:m['labels'].update(**{'managed-by':'manual'}))
    def test_no_labels(self):self.bad(lambda m:m.pop('labels'))
    def test_delete(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["delete"]))
    def test_replace(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["create","delete"]))
    def test_invalid_action(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["destroy"]))
    def test_unapproved_type(self):self.bad_plan(lambda p:p["resource_changes"][0].update(type="google_container_cluster"))
    def test_missing_plan(self):self.assertTrue(validate(SAFE,{},POLICY))
    def test_invalid_manifest(self):self.assertTrue(validate([],PLAN,POLICY))
    def test_fail_open_policy(self):
        p=copy.deepcopy(POLICY);p["deny_destructive_actions"]=False;self.assertTrue(validate(SAFE,PLAN,p))
    def test_noop_allowed(self):
        p=copy.deepcopy(PLAN);p["resource_changes"][0]["change"]["actions"]=["no-op"];self.assertEqual(validate(SAFE,p,POLICY),[])
if __name__=="__main__":unittest.main()
