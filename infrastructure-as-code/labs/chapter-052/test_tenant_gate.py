import copy,json,unittest
from pathlib import Path
from tenant_gate import validate
ROOT=Path(__file__).parent
SAFE=json.loads((ROOT/"fixtures/tenant-safe.json").read_text())
UNSAFE=json.loads((ROOT/"fixtures/tenant-unsafe.json").read_text())
PLAN=json.loads((ROOT/"fixtures/plan-safe.json").read_text())
DESTRUCTIVE=json.loads((ROOT/"fixtures/plan-destructive.json").read_text())
POLICY=json.loads((ROOT/"tenant-policy.json").read_text())
class TenantGateTests(unittest.TestCase):
    def bad(self,fn):
        m=copy.deepcopy(SAFE);fn(m);self.assertTrue(validate(m,PLAN,POLICY))
    def bad_plan(self,fn):
        p=copy.deepcopy(PLAN);fn(p);self.assertTrue(validate(SAFE,p,POLICY))
    def test_safe(self):self.assertEqual(validate(SAFE,PLAN,POLICY),[])
    def test_unsafe(self):self.assertTrue(validate(UNSAFE,DESTRUCTIVE,POLICY))
    def test_destructive(self):self.assertTrue(validate(SAFE,DESTRUCTIVE,POLICY))
    def test_environment(self):self.bad(lambda m:m.update(environment='invalid'))
    def test_cluster_name(self):self.bad(lambda m:m.update(cluster_name='BAD'))
    def test_namespace(self):self.bad(lambda m:m.update(namespace='BAD'))
    def test_owner(self):self.bad(lambda m:m.update(owner=''))
    def test_ticket(self):self.bad(lambda m:m.update(change_ticket=''))
    def test_state_namespace(self):self.bad(lambda m:m.update(state_namespace='iac-dev'))
    def test_namespace_namespace_owner_verified(self):self.bad(lambda m:m['namespace'].update(namespace_owner_verified=False))
    def test_namespace_quota_enabled(self):self.bad(lambda m:m['namespace'].update(quota_enabled=False))
    def test_namespace_limitrange_enabled(self):self.bad(lambda m:m['namespace'].update(limitrange_enabled=False))
    def test_namespace_psa_restricted(self):self.bad(lambda m:m['namespace'].update(psa_restricted=False))
    def test_namespace_namespace_deletion_protected(self):self.bad(lambda m:m['namespace'].update(namespace_deletion_protected=False))
    def test_no_namespace(self):self.bad(lambda m:m.pop('namespace'))
    def test_rbac_dedicated_service_accounts(self):self.bad(lambda m:m['rbac'].update(dedicated_service_accounts=False))
    def test_rbac_rbac_least_privilege(self):self.bad(lambda m:m['rbac'].update(rbac_least_privilege=False))
    def test_rbac_rbac_scoped_rolebindings(self):self.bad(lambda m:m['rbac'].update(rbac_scoped_rolebindings=False))
    def test_rbac_effective_permissions_tested(self):self.bad(lambda m:m['rbac'].update(effective_permissions_tested=False))
    def test_rbac_token_automount_disabled(self):self.bad(lambda m:m['rbac'].update(token_automount_disabled=False))
    def test_no_rbac(self):self.bad(lambda m:m.pop('rbac'))
    def test_network_default_deny_ingress(self):self.bad(lambda m:m['network'].update(default_deny_ingress=False))
    def test_network_default_deny_egress(self):self.bad(lambda m:m['network'].update(default_deny_egress=False))
    def test_network_dns_egress_explicit(self):self.bad(lambda m:m['network'].update(dns_egress_explicit=False))
    def test_network_database_egress_scoped(self):self.bad(lambda m:m['network'].update(database_egress_scoped=False))
    def test_network_cni_enforcement_tested(self):self.bad(lambda m:m['network'].update(cni_enforcement_tested=False))
    def test_no_network(self):self.bad(lambda m:m.pop('network'))
    def test_operations_audit_logs_enabled(self):self.bad(lambda m:m['operations'].update(audit_logs_enabled=False))
    def test_operations_monitoring_enabled(self):self.bad(lambda m:m['operations'].update(monitoring_enabled=False))
    def test_operations_tenant_cost_labels(self):self.bad(lambda m:m['operations'].update(tenant_cost_labels=False))
    def test_operations_backup_reviewed(self):self.bad(lambda m:m['operations'].update(backup_reviewed=False))
    def test_operations_dbre_approved(self):self.bad(lambda m:m['operations'].update(dbre_approved=False))
    def test_operations_security_approved(self):self.bad(lambda m:m['operations'].update(security_approved=False))
    def test_operations_change_approved(self):self.bad(lambda m:m['operations'].update(change_approved=False))
    def test_no_operations(self):self.bad(lambda m:m.pop('operations'))
    def test_wildcard_cluster_admin(self):self.bad(lambda m:m['rbac'].update(wildcard_cluster_admin=True))
    def test_default_service_account_used(self):self.bad(lambda m:m['rbac'].update(default_service_account_used=True))
    def test_broad_egress(self):self.bad(lambda m:m['network'].update(broad_egress=True))
    def test_unapproved_destroy(self):self.bad(lambda m:m['operations'].update(unapproved_destroy=True))
    def test_environment_label(self):self.bad(lambda m:m['labels'].update(environment='dev'))
    def test_owner_label(self):self.bad(lambda m:m['labels'].update(owner=''))
    def test_managedby_label(self):self.bad(lambda m:m['labels'].update(**{'managed-by':'manual'}))
    def test_no_labels(self):self.bad(lambda m:m.pop('labels'))
    def test_delete(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["delete"]))
    def test_replace(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["create","delete"]))
    def test_invalid_action(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["destroy"]))
    def test_unapproved_type(self):self.bad_plan(lambda p:p["resource_changes"][0].update(type="kubernetes_namespace_v1"))
    def test_missing_plan(self):self.assertTrue(validate(SAFE,{},POLICY))
    def test_invalid_manifest(self):self.assertTrue(validate([],PLAN,POLICY))
    def test_fail_open_policy(self):
        p=copy.deepcopy(POLICY);p["deny_destructive_actions"]=False;self.assertTrue(validate(SAFE,PLAN,p))
    def test_noop_allowed(self):
        p=copy.deepcopy(PLAN);p["resource_changes"][0]["change"]["actions"]=["no-op"];self.assertEqual(validate(SAFE,p,POLICY),[])
if __name__=="__main__":unittest.main()
