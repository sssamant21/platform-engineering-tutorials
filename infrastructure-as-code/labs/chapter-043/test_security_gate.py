import copy,json,unittest
from pathlib import Path
from security_gate import validate
ROOT=Path(__file__).parent
SAFE=json.loads((ROOT/"fixtures/security-safe.json").read_text())
UNSAFE=json.loads((ROOT/"fixtures/security-unsafe.json").read_text())
PLAN=json.loads((ROOT/"fixtures/plan-safe.json").read_text())
DESTRUCTIVE=json.loads((ROOT/"fixtures/plan-destructive.json").read_text())
POLICY=json.loads((ROOT/"security-policy.json").read_text())
class SecurityGateTests(unittest.TestCase):
    def bad(self,fn):
        m=copy.deepcopy(SAFE);fn(m);self.assertTrue(validate(m,PLAN,POLICY))
    def bad_plan(self,fn):
        p=copy.deepcopy(PLAN);fn(p);self.assertTrue(validate(SAFE,p,POLICY))
    def test_safe(self):self.assertEqual(validate(SAFE,PLAN,POLICY),[])
    def test_unsafe(self):self.assertTrue(validate(UNSAFE,DESTRUCTIVE,POLICY))
    def test_destructive(self):self.assertTrue(validate(SAFE,DESTRUCTIVE,POLICY))
    def test_environment(self):self.bad(lambda m:m.update(environment="invalid"))
    def test_tenant(self):self.bad(lambda m:m.update(tenant_id="invalid"))
    def test_subscription(self):self.bad(lambda m:m.update(subscription_id="invalid"))
    def test_owner(self):self.bad(lambda m:m.update(owner=""))
    def test_ticket(self):self.bad(lambda m:m.update(change_ticket=""))
    def test_state_namespace(self):self.bad(lambda m:m.update(state_namespace="iac-dev"))
    def test_oidc_disabled(self):self.bad(lambda m:m["identity"].update(oidc_enabled=False))
    def test_static_secret(self):self.bad(lambda m:m["identity"].update(static_client_secret_used=True))
    def test_oidc_issuer(self):self.bad(lambda m:m["identity"].update(oidc_issuer="https://evil.example"))
    def test_oidc_audience(self):self.bad(lambda m:m["identity"].update(oidc_audience="wrong"))
    def test_oidc_subject_wildcard(self):self.bad(lambda m:m["identity"].update(oidc_subject="repo:*"))
    def test_oidc_subject_dev(self):self.bad(lambda m:m["identity"].update(oidc_subject="repo:example-org/platform-infra:environment:dev"))
    def test_managed_identity(self):self.bad(lambda m:m["identity"].update(managed_identity_enabled=False))
    def test_no_identity(self):self.bad(lambda m:m.pop("identity"))
    def test_rbac_least_privilege(self):self.bad(lambda m:m["rbac"].update(least_privilege_reviewed=False))
    def test_rbac_audit(self):self.bad(lambda m:m["rbac"].update(role_assignments_audited=False))
    def test_privileged_assignment(self):self.bad(lambda m:m["rbac"].update(privileged_role_assignment_used=True))
    def test_wildcard_scope(self):self.bad(lambda m:m["rbac"].update(wildcard_scope_used=True))
    def test_no_rbac(self):self.bad(lambda m:m.pop("rbac"))
    def test_vault_rbac(self):self.bad(lambda m:m["key_vault"].update(rbac_enabled=False))
    def test_vault_private(self):self.bad(lambda m:m["key_vault"].update(private_access=False))
    def test_purge_protection(self):self.bad(lambda m:m["key_vault"].update(purge_protection=False))
    def test_soft_delete(self):self.bad(lambda m:m["key_vault"].update(soft_delete_enabled=False))
    def test_rotation(self):self.bad(lambda m:m["key_vault"].update(secret_rotation_enabled=False))
    def test_diagnostics(self):self.bad(lambda m:m["key_vault"].update(diagnostics_enabled=False))
    def test_cmk_recovery(self):self.bad(lambda m:m["key_vault"].update(cmk_recovery_tested=False))
    def test_plaintext_state(self):self.bad(lambda m:m["key_vault"].update(plaintext_secret_in_state=True))
    def test_no_vault(self):self.bad(lambda m:m.pop("key_vault"))
    def test_state_encryption(self):self.bad(lambda m:m["state"].update(encrypted=False))
    def test_state_private(self):self.bad(lambda m:m["state"].update(private=False))
    def test_state_azuread(self):self.bad(lambda m:m["state"].update(azuread_auth=False))
    def test_state_locking(self):self.bad(lambda m:m["state"].update(locking_enabled=False))
    def test_state_versioning(self):self.bad(lambda m:m["state"].update(versioning_enabled=False))
    def test_no_state(self):self.bad(lambda m:m.pop("state"))
    def test_activity_logs(self):self.bad(lambda m:m["audit"].update(activity_logs_enabled=False))
    def test_security_review(self):self.bad(lambda m:m["audit"].update(security_reviewed=False))
    def test_dbre_approval(self):self.bad(lambda m:m["audit"].update(dbre_approved=False))
    def test_rotation_drill(self):self.bad(lambda m:m["audit"].update(rotation_drill_passed=False))
    def test_no_audit(self):self.bad(lambda m:m.pop("audit"))
    def test_environment_tag(self):self.bad(lambda m:m["tags"].update(Environment="dev"))
    def test_owner_tag(self):self.bad(lambda m:m["tags"].update(Owner=""))
    def test_managedby_tag(self):self.bad(lambda m:m["tags"].update(ManagedBy="manual"))
    def test_no_tags(self):self.bad(lambda m:m.pop("tags"))
    def test_delete(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["delete"]))
    def test_replace(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["create","delete"]))
    def test_invalid_action(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["destroy"]))
    def test_unapproved_resource(self):self.bad_plan(lambda p:p["resource_changes"][0].update(type="azurerm_key_vault"))
    def test_missing_plan(self):self.assertTrue(validate(SAFE,{},POLICY))
    def test_bad_manifest(self):self.assertTrue(validate([],PLAN,POLICY))
    def test_fail_open_policy(self):
        p=copy.deepcopy(POLICY);p["deny_destructive_actions"]=False;self.assertTrue(validate(SAFE,PLAN,p))
    def test_noop_allowed(self):
        p=copy.deepcopy(PLAN);p["resource_changes"][0]["change"]["actions"]=["no-op"];self.assertEqual(validate(SAFE,p,POLICY),[])
if __name__=="__main__":unittest.main()
