import copy,json,unittest
from pathlib import Path
from security_gate import validate
ROOT=Path(__file__).parent
SAFE=json.loads((ROOT/"fixtures/security-safe.json").read_text())
UNSAFE=json.loads((ROOT/"fixtures/security-unsafe.json").read_text())
PLAN=json.loads((ROOT/"fixtures/plan-safe.json").read_text())
DESTRUCTIVE=json.loads((ROOT/"fixtures/plan-destructive.json").read_text())
POLICY=json.loads((ROOT/"security-policy.json").read_text())
class SecurityGateTests(unittest.TestCase):
    def bad(self,fn):
        m=copy.deepcopy(SAFE);fn(m);self.assertTrue(validate(m,PLAN,POLICY))
    def bad_plan(self,fn):
        p=copy.deepcopy(PLAN);fn(p);self.assertTrue(validate(SAFE,p,POLICY))
    def test_safe(self):self.assertEqual(validate(SAFE,PLAN,POLICY),[])
    def test_unsafe(self):self.assertTrue(validate(UNSAFE,DESTRUCTIVE,POLICY))
    def test_destructive(self):self.assertTrue(validate(SAFE,DESTRUCTIVE,POLICY))
    def test_environment(self):self.bad(lambda m:m.update(environment="invalid"))
    def test_account_short(self):self.bad(lambda m:m.update(aws_account_id="123"))
    def test_account_alpha(self):self.bad(lambda m:m.update(aws_account_id="a"*12))
    def test_owner(self):self.bad(lambda m:m.update(owner=""))
    def test_ticket(self):self.bad(lambda m:m.update(change_ticket=""))
    def test_state_namespace(self):self.bad(lambda m:m.update(state_namespace="iac-dev-444455556666"))
    def test_static_keys(self):self.bad(lambda m:m["identity"].update(static_access_keys=True))
    def test_no_short_lived(self):self.bad(lambda m:m["identity"].update(short_lived_credentials=False))
    def test_oidc_issuer(self):self.bad(lambda m:m["identity"].update(oidc_issuer="evil.example"))
    def test_oidc_audience(self):self.bad(lambda m:m["identity"].update(oidc_audience="other"))
    def test_oidc_wildcard(self):self.bad(lambda m:m["identity"].update(oidc_subject="repo:*"))
    def test_oidc_wrong_environment(self):self.bad(lambda m:m["identity"].update(oidc_subject="repo:example-org/platform-infra:environment:dev"))
    def test_oidc_branch(self):self.bad(lambda m:m["identity"].update(oidc_subject="repo:example-org/platform-infra:ref:refs/heads/main"))
    def test_least_privilege(self):self.bad(lambda m:m["identity"].update(least_privilege_reviewed=False))
    def test_passrole(self):self.bad(lambda m:m["identity"].update(passrole_restricted=False))
    def test_wildcard_admin(self):self.bad(lambda m:m["identity"].update(wildcard_admin=True))
    def test_no_identity(self):self.bad(lambda m:m.pop("identity"))
    def test_kms_customer_managed(self):self.bad(lambda m:m["kms"].update(customer_managed=False))
    def test_kms_rotation(self):self.bad(lambda m:m["kms"].update(rotation_enabled=False))
    def test_kms_policy(self):self.bad(lambda m:m["kms"].update(key_policy_reviewed=False))
    def test_kms_short_window(self):self.bad(lambda m:m["kms"].update(deletion_window_days=7))
    def test_kms_long_window(self):self.bad(lambda m:m["kms"].update(deletion_window_days=31))
    def test_kms_bool_window(self):self.bad(lambda m:m["kms"].update(deletion_window_days=True))
    def test_kms_unrestricted_decrypt(self):self.bad(lambda m:m["kms"].update(unrestricted_decrypt=True))
    def test_no_kms(self):self.bad(lambda m:m.pop("kms"))
    def test_plaintext_in_state(self):self.bad(lambda m:m["secrets"].update(plaintext_in_state=True))
    def test_secret_rotation(self):self.bad(lambda m:m["secrets"].update(rotation_enabled=False))
    def test_public_secret_policy(self):self.bad(lambda m:m["secrets"].update(resource_policy_public=True))
    def test_no_runtime_retrieval(self):self.bad(lambda m:m["secrets"].update(runtime_identity_retrieval=False))
    def test_no_secrets(self):self.bad(lambda m:m.pop("secrets"))
    def test_cloudtrail(self):self.bad(lambda m:m["audit"].update(cloudtrail_enabled=False))
    def test_config(self):self.bad(lambda m:m["audit"].update(config_enabled=False))
    def test_security_review(self):self.bad(lambda m:m["audit"].update(security_reviewed=False))
    def test_no_audit(self):self.bad(lambda m:m.pop("audit"))
    def test_environment_tag(self):self.bad(lambda m:m["tags"].update(Environment="dev"))
    def test_owner_tag(self):self.bad(lambda m:m["tags"].update(Owner=""))
    def test_managedby_tag(self):self.bad(lambda m:m["tags"].update(ManagedBy="manual"))
    def test_no_tags(self):self.bad(lambda m:m.pop("tags"))
    def test_delete(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["delete"]))
    def test_replace(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["create","delete"]))
    def test_bad_action(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["destroy"]))
    def test_unapproved_type(self):self.bad_plan(lambda p:p["resource_changes"][0].update(type="aws_kms_key"))
    def test_missing_plan(self):self.assertTrue(validate(SAFE,{},POLICY))
    def test_bad_manifest(self):self.assertTrue(validate([],PLAN,POLICY))
    def test_fail_open_policy(self):
        p=copy.deepcopy(POLICY);p["deny_destructive_actions"]=False;self.assertTrue(validate(SAFE,PLAN,p))
    def test_noop_allowed(self):
        p=copy.deepcopy(PLAN);p["resource_changes"][0]["change"]["actions"]=["no-op"];self.assertEqual(validate(SAFE,p,POLICY),[])
if __name__=="__main__":unittest.main()
