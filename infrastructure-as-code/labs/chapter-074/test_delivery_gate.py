    def test_missing_delivery(self):self.bad(lambda m:m.pop('delivery'))
    def test_dbre_backup_verified(self):self.bad(lambda m:m['dbre'].update(backup_verified=False))
    def test_dbre_restore_rehearsed(self):self.bad(lambda m:m['dbre'].update(restore_rehearsed=False))
