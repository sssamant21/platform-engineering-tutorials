import copy,json,unittest
from pathlib import Path
from capstone_gate import validate
ROOT=Path(__file__).parent
SAFE=json.loads((ROOT/"fixtures/capstone-safe.json").read_text())
UNSAFE=json.loads((ROOT/"fixtures/capstone-unsafe.json").read_text())
PLAN=json.loads((ROOT/"fixtures/plan-safe.json").read_text())
DESTRUCTIVE=json.loads((ROOT/"fixtures/plan-destructive.json").read_text())
POLICY=json.loads((ROOT/"capstone-policy.json").read_text())
class CapstoneGateTests(unittest.TestCase):
    def bad(self,fn):
        m=copy.deepcopy(SAFE);fn(m);self.assertTrue(validate(m,PLAN,POLICY))
    def bad_plan(self,fn):
        p=copy.deepcopy(PLAN);fn(p);self.assertTrue(validate(SAFE,p,POLICY))
    def test_safe(self):self.assertEqual(validate(SAFE,PLAN,POLICY),[])
    def test_unsafe(self):self.assertTrue(validate(UNSAFE,DESTRUCTIVE,POLICY))
    def test_destructive(self):self.assertTrue(validate(SAFE,DESTRUCTIVE,POLICY))
    def test_environment(self):self.bad(lambda m:m.update(environment='invalid'))
    def test_cluster_name(self):self.bad(lambda m:m.update(cluster_name='BAD'))
    def test_namespace(self):self.bad(lambda m:m.update(namespace='BAD'))
    def test_owner(self):self.bad(lambda m:m.update(owner=''))
    def test_ticket(self):self.bad(lambda m:m.update(change_ticket=''))
    def test_state_namespace(self):self.bad(lambda m:m.update(state_namespace='iac-dev'))
    def test_foundation_cluster_context_verified(self):self.bad(lambda m:m['foundation'].update(cluster_context_verified=False))
    def test_foundation_state_isolated(self):self.bad(lambda m:m['foundation'].update(state_isolated=False))
    def test_foundation_cni_enforced(self):self.bad(lambda m:m['foundation'].update(cni_enforced=False))
    def test_foundation_csi_ready(self):self.bad(lambda m:m['foundation'].update(csi_ready=False))
    def test_foundation_observability_ready(self):self.bad(lambda m:m['foundation'].update(observability_ready=False))
    def test_foundation_capacity_reviewed(self):self.bad(lambda m:m['foundation'].update(capacity_reviewed=False))
    def test_no_foundation(self):self.bad(lambda m:m.pop('foundation'))
    def test_security_dedicated_service_accounts(self):self.bad(lambda m:m['security'].update(dedicated_service_accounts=False))
    def test_security_rbac_least_privilege(self):self.bad(lambda m:m['security'].update(rbac_least_privilege=False))
    def test_security_psa_restricted(self):self.bad(lambda m:m['security'].update(psa_restricted=False))
    def test_security_default_deny_network(self):self.bad(lambda m:m['security'].update(default_deny_network=False))
    def test_security_dns_db_egress_scoped(self):self.bad(lambda m:m['security'].update(dns_db_egress_scoped=False))
    def test_security_quotas_enforced(self):self.bad(lambda m:m['security'].update(quotas_enforced=False))
    def test_security_secrets_excluded_from_state(self):self.bad(lambda m:m['security'].update(secrets_excluded_from_state=False))
    def test_no_security(self):self.bad(lambda m:m.pop('security'))
    def test_delivery_provider_chart_pinned(self):self.bad(lambda m:m['delivery'].update(provider_chart_pinned=False))
    def test_delivery_chart_provenance_reviewed(self):self.bad(lambda m:m['delivery'].update(chart_provenance_reviewed=False))
    def test_delivery_crd_staged(self):self.bad(lambda m:m['delivery'].update(crd_staged=False))
    def test_delivery_single_gitops_owner(self):self.bad(lambda m:m['delivery'].update(single_gitops_owner=False))
    def test_delivery_rollout_tested(self):self.bad(lambda m:m['delivery'].update(rollout_tested=False))
    def test_delivery_pdb_reviewed(self):self.bad(lambda m:m['delivery'].update(pdb_reviewed=False))
    def test_delivery_rollback_tested(self):self.bad(lambda m:m['delivery'].update(rollback_tested=False))
    def test_no_delivery(self):self.bad(lambda m:m.pop('delivery'))
    def test_operations_backup_tested(self):self.bad(lambda m:m['operations'].update(backup_tested=False))
    def test_operations_restore_tested(self):self.bad(lambda m:m['operations'].update(restore_tested=False))
    def test_operations_rpo_rto_measured(self):self.bad(lambda m:m['operations'].update(rpo_rto_measured=False))
    def test_operations_game_day_completed(self):self.bad(lambda m:m['operations'].update(game_day_completed=False))
    def test_operations_audit_logs_enabled(self):self.bad(lambda m:m['operations'].update(audit_logs_enabled=False))
    def test_operations_security_approved(self):self.bad(lambda m:m['operations'].update(security_approved=False))
    def test_operations_dbre_approved(self):self.bad(lambda m:m['operations'].update(dbre_approved=False))
    def test_operations_change_approved(self):self.bad(lambda m:m['operations'].update(change_approved=False))
    def test_no_operations(self):self.bad(lambda m:m.pop('operations'))
    def test_wildcard_cluster_admin(self):self.bad(lambda m:m['security'].update(wildcard_cluster_admin=True))
    def test_competing_reconciler(self):self.bad(lambda m:m['delivery'].update(competing_reconciler=True))
    def test_unapproved_destroy(self):self.bad(lambda m:m['operations'].update(unapproved_destroy=True))
    def test_unapproved_pvc_delete(self):self.bad(lambda m:m['operations'].update(unapproved_pvc_delete=True))
    def test_environment_label(self):self.bad(lambda m:m['labels'].update(environment='dev'))
    def test_owner_label(self):self.bad(lambda m:m['labels'].update(owner=''))
    def test_managedby_label(self):self.bad(lambda m:m['labels'].update(**{'managed-by':'manual'}))
    def test_no_labels(self):self.bad(lambda m:m.pop('labels'))
    def test_delete(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["delete"]))
    def test_replace(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["create","delete"]))
    def test_invalid_action(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["destroy"]))
    def test_unapproved_type(self):self.bad_plan(lambda p:p["resource_changes"][0].update(type="kubernetes_persistent_volume_claim_v1"))
    def test_missing_plan(self):self.assertTrue(validate(SAFE,{},POLICY))
    def test_invalid_manifest(self):self.assertTrue(validate([],PLAN,POLICY))
    def test_fail_open_policy(self):
        p=copy.deepcopy(POLICY);p["deny_destructive_actions"]=False;self.assertTrue(validate(SAFE,PLAN,p))
    def test_noop_allowed(self):
        p=copy.deepcopy(PLAN);p["resource_changes"][0]["change"]["actions"]=["no-op"];self.assertEqual(validate(SAFE,p,POLICY),[])
if __name__=="__main__":unittest.main()
