import copy,json,unittest
from pathlib import Path
from data_gate import validate
ROOT=Path(__file__).parent
SAFE=json.loads((ROOT/"fixtures/data-safe.json").read_text())
UNSAFE=json.loads((ROOT/"fixtures/data-unsafe.json").read_text())
PLAN=json.loads((ROOT/"fixtures/plan-safe.json").read_text())
DESTRUCTIVE=json.loads((ROOT/"fixtures/plan-destructive.json").read_text())
POLICY=json.loads((ROOT/"data-policy.json").read_text())
class DataGateTests(unittest.TestCase):
    def bad(self,fn):
        m=copy.deepcopy(SAFE);fn(m);self.assertTrue(validate(m,PLAN,POLICY))
    def bad_plan(self,fn):
        p=copy.deepcopy(PLAN);fn(p);self.assertTrue(validate(SAFE,p,POLICY))
    def test_safe(self):self.assertEqual(validate(SAFE,PLAN,POLICY),[])
    def test_unsafe(self):self.assertTrue(validate(UNSAFE,DESTRUCTIVE,POLICY))
    def test_destructive(self):self.assertTrue(validate(SAFE,DESTRUCTIVE,POLICY))
    def test_environment(self):self.bad(lambda m:m.update(environment='invalid'))
    def test_project_id(self):self.bad(lambda m:m.update(project_id='INVALID'))
    def test_region(self):self.bad(lambda m:m.update(region='europe-west1'))
    def test_owner(self):self.bad(lambda m:m.update(owner=''))
    def test_ticket(self):self.bad(lambda m:m.update(change_ticket=''))
    def test_state_namespace(self):self.bad(lambda m:m.update(state_namespace='iac-dev'))
    def test_database_db_ha(self):self.bad(lambda m:m['database'].update(db_ha=False))
    def test_database_db_pitr(self):self.bad(lambda m:m['database'].update(db_pitr=False))
    def test_database_db_backup_enabled(self):self.bad(lambda m:m['database'].update(db_backup_enabled=False))
    def test_database_db_restore_tested(self):self.bad(lambda m:m['database'].update(db_restore_tested=False))
    def test_database_db_private_connectivity(self):self.bad(lambda m:m['database'].update(db_private_connectivity=False))
    def test_database_db_connection_pool_reviewed(self):self.bad(lambda m:m['database'].update(db_connection_pool_reviewed=False))
    def test_database_db_replication_reviewed(self):self.bad(lambda m:m['database'].update(db_replication_reviewed=False))
    def test_no_database(self):self.bad(lambda m:m.pop('database'))
    def test_storage_storage_public_access_prevention(self):self.bad(lambda m:m['storage'].update(storage_public_access_prevention=False))
    def test_storage_storage_uniform_access(self):self.bad(lambda m:m['storage'].update(storage_uniform_access=False))
    def test_storage_storage_versioning(self):self.bad(lambda m:m['storage'].update(storage_versioning=False))
    def test_storage_storage_retention_reviewed(self):self.bad(lambda m:m['storage'].update(storage_retention_reviewed=False))
    def test_storage_storage_lifecycle_reviewed(self):self.bad(lambda m:m['storage'].update(storage_lifecycle_reviewed=False))
    def test_storage_storage_encrypted(self):self.bad(lambda m:m['storage'].update(storage_encrypted=False))
    def test_storage_storage_recovery_tested(self):self.bad(lambda m:m['storage'].update(storage_recovery_tested=False))
    def test_no_storage(self):self.bad(lambda m:m.pop('storage'))
    def test_security_kms_enabled(self):self.bad(lambda m:m['security'].update(kms_enabled=False))
    def test_security_kms_recovery_tested(self):self.bad(lambda m:m['security'].update(kms_recovery_tested=False))
    def test_security_kms_service_agent_reviewed(self):self.bad(lambda m:m['security'].update(kms_service_agent_reviewed=False))
    def test_security_workload_identity(self):self.bad(lambda m:m['security'].update(workload_identity=False))
    def test_security_private_dns_reviewed(self):self.bad(lambda m:m['security'].update(private_dns_reviewed=False))
    def test_no_security(self):self.bad(lambda m:m.pop('security'))
    def test_operations_monitoring_enabled(self):self.bad(lambda m:m['operations'].update(monitoring_enabled=False))
    def test_operations_audit_logs_enabled(self):self.bad(lambda m:m['operations'].update(audit_logs_enabled=False))
    def test_operations_dr_runbook_tested(self):self.bad(lambda m:m['operations'].update(dr_runbook_tested=False))
    def test_operations_rpo_rto_measured(self):self.bad(lambda m:m['operations'].update(rpo_rto_measured=False))
    def test_operations_dbre_approved(self):self.bad(lambda m:m['operations'].update(dbre_approved=False))
    def test_operations_security_approved(self):self.bad(lambda m:m['operations'].update(security_approved=False))
    def test_operations_change_approved(self):self.bad(lambda m:m['operations'].update(change_approved=False))
    def test_no_operations(self):self.bad(lambda m:m.pop('operations'))
    def test_public_db(self):self.bad(lambda m:m['database'].update(db_public_ingress=True))
    def test_static_key(self):self.bad(lambda m:m['security'].update(static_keys=True))
    def test_secret_in_state(self):self.bad(lambda m:m['security'].update(secret_payload_in_state=True))
    def test_environment_label(self):self.bad(lambda m:m['labels'].update(environment='dev'))
    def test_owner_label(self):self.bad(lambda m:m['labels'].update(owner=''))
    def test_managedby_label(self):self.bad(lambda m:m['labels'].update(**{'managed-by':'manual'}))
    def test_no_labels(self):self.bad(lambda m:m.pop('labels'))
    def test_delete(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["delete"]))
    def test_replace(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["create","delete"]))
    def test_invalid_action(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["destroy"]))
    def test_unapproved_type(self):self.bad_plan(lambda p:p["resource_changes"][0].update(type="google_sql_database_instance"))
    def test_missing_plan(self):self.assertTrue(validate(SAFE,{},POLICY))
    def test_invalid_manifest(self):self.assertTrue(validate([],PLAN,POLICY))
    def test_fail_open_policy(self):
        p=copy.deepcopy(POLICY);p["deny_destructive_actions"]=False;self.assertTrue(validate(SAFE,PLAN,p))
    def test_noop_allowed(self):
        p=copy.deepcopy(PLAN);p["resource_changes"][0]["change"]["actions"]=["no-op"];self.assertEqual(validate(SAFE,p,POLICY),[])
if __name__=="__main__":unittest.main()
