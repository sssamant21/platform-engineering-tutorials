import copy,json,unittest
from pathlib import Path
from data_gate import validate
ROOT=Path(__file__).parent
SAFE=json.loads((ROOT/"fixtures/data-safe.json").read_text())
UNSAFE=json.loads((ROOT/"fixtures/data-unsafe.json").read_text())
PLAN=json.loads((ROOT/"fixtures/plan-safe.json").read_text())
DESTRUCTIVE=json.loads((ROOT/"fixtures/plan-destructive.json").read_text())
POLICY=json.loads((ROOT/"data-policy.json").read_text())
class DataGateTests(unittest.TestCase):
    def bad(self,fn):
        m=copy.deepcopy(SAFE);fn(m);self.assertTrue(validate(m,PLAN,POLICY))
    def bad_plan(self,fn):
        p=copy.deepcopy(PLAN);fn(p);self.assertTrue(validate(SAFE,p,POLICY))
    def test_safe(self):self.assertEqual(validate(SAFE,PLAN,POLICY),[])
    def test_unsafe(self):self.assertTrue(validate(UNSAFE,DESTRUCTIVE,POLICY))
    def test_destructive(self):self.assertTrue(validate(SAFE,DESTRUCTIVE,POLICY))
    def test_environment(self):self.bad(lambda m:m.update(environment='invalid'))
    def test_subscription(self):self.bad(lambda m:m.update(subscription_id='invalid'))
    def test_location(self):self.bad(lambda m:m.update(location='westeurope'))
    def test_owner(self):self.bad(lambda m:m.update(owner=''))
    def test_ticket(self):self.bad(lambda m:m.update(change_ticket=''))
    def test_state_namespace(self):self.bad(lambda m:m.update(state_namespace='iac-dev'))
    def test_database_postgresql_private(self):self.bad(lambda m:m['database'].update(postgresql_private=False))
    def test_database_postgresql_tls(self):self.bad(lambda m:m['database'].update(postgresql_tls=False))
    def test_database_postgresql_ha(self):self.bad(lambda m:m['database'].update(postgresql_ha=False))
    def test_database_postgresql_pitr(self):self.bad(lambda m:m['database'].update(postgresql_pitr=False))
    def test_database_postgresql_backup_retention_reviewed(self):self.bad(lambda m:m['database'].update(postgresql_backup_retention_reviewed=False))
    def test_database_sql_private(self):self.bad(lambda m:m['database'].update(sql_private=False))
    def test_database_sql_backup_enabled(self):self.bad(lambda m:m['database'].update(sql_backup_enabled=False))
    def test_database_sql_restore_tested(self):self.bad(lambda m:m['database'].update(sql_restore_tested=False))
    def test_database_connection_pool_reviewed(self):self.bad(lambda m:m['database'].update(connection_pool_reviewed=False))
    def test_no_database(self):self.bad(lambda m:m.pop('database'))
    def test_storage_private(self):self.bad(lambda m:m['storage'].update(private=False))
    def test_storage_versioning(self):self.bad(lambda m:m['storage'].update(versioning=False))
    def test_storage_soft_delete(self):self.bad(lambda m:m['storage'].update(soft_delete=False))
    def test_storage_encrypted(self):self.bad(lambda m:m['storage'].update(encrypted=False))
    def test_storage_shared_keys_disabled(self):self.bad(lambda m:m['storage'].update(shared_keys_disabled=False))
    def test_storage_replication_reviewed(self):self.bad(lambda m:m['storage'].update(replication_reviewed=False))
    def test_storage_restore_tested(self):self.bad(lambda m:m['storage'].update(restore_tested=False))
    def test_no_storage(self):self.bad(lambda m:m.pop('storage'))
    def test_security_key_vault_private(self):self.bad(lambda m:m['security'].update(key_vault_private=False))
    def test_security_purge_protection(self):self.bad(lambda m:m['security'].update(purge_protection=False))
    def test_security_cmk_access_reviewed(self):self.bad(lambda m:m['security'].update(cmk_access_reviewed=False))
    def test_security_cmk_recovery_tested(self):self.bad(lambda m:m['security'].update(cmk_recovery_tested=False))
    def test_security_managed_identity_enabled(self):self.bad(lambda m:m['security'].update(managed_identity_enabled=False))
    def test_no_security(self):self.bad(lambda m:m.pop('security'))
    def test_recovery_backup_enabled(self):self.bad(lambda m:m['recovery'].update(backup_enabled=False))
    def test_recovery_restore_drill_tested(self):self.bad(lambda m:m['recovery'].update(restore_drill_tested=False))
    def test_recovery_geo_recovery_reviewed(self):self.bad(lambda m:m['recovery'].update(geo_recovery_reviewed=False))
    def test_recovery_integrity_verified(self):self.bad(lambda m:m['recovery'].update(integrity_verified=False))
    def test_no_recovery(self):self.bad(lambda m:m.pop('recovery'))
    def test_audit_diagnostics_enabled(self):self.bad(lambda m:m['audit'].update(diagnostics_enabled=False))
    def test_audit_alerts_enabled(self):self.bad(lambda m:m['audit'].update(alerts_enabled=False))
    def test_audit_dbre_approved(self):self.bad(lambda m:m['audit'].update(dbre_approved=False))
    def test_audit_security_approved(self):self.bad(lambda m:m['audit'].update(security_approved=False))
    def test_audit_change_approved(self):self.bad(lambda m:m['audit'].update(change_approved=False))
    def test_no_audit(self):self.bad(lambda m:m.pop('audit'))
    def test_plaintext_secret(self):self.bad(lambda m:m['security'].update(plaintext_secret_in_state=True))
    def test_rpo(self):self.bad(lambda m:m['recovery'].update(rpo_minutes=999))
    def test_rto(self):self.bad(lambda m:m['recovery'].update(rto_minutes=999))
    def test_rto_zero(self):self.bad(lambda m:m['recovery'].update(rto_minutes=0))
    def test_rpo_string(self):self.bad(lambda m:m['recovery'].update(rpo_minutes='60'))
    def test_environment_tag(self):self.bad(lambda m:m['tags'].update(Environment='dev'))
    def test_owner_tag(self):self.bad(lambda m:m['tags'].update(Owner=''))
    def test_managedby_tag(self):self.bad(lambda m:m['tags'].update(ManagedBy='manual'))
    def test_no_tags(self):self.bad(lambda m:m.pop('tags'))
    def test_delete(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["delete"]))
    def test_replace(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["create","delete"]))
    def test_invalid_action(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["destroy"]))
    def test_unapproved_type(self):self.bad_plan(lambda p:p["resource_changes"][0].update(type="azurerm_postgresql_flexible_server"))
    def test_missing_plan(self):self.assertTrue(validate(SAFE,{},POLICY))
    def test_invalid_manifest(self):self.assertTrue(validate([],PLAN,POLICY))
    def test_fail_open_policy(self):
        p=copy.deepcopy(POLICY);p["deny_destructive_actions"]=False;self.assertTrue(validate(SAFE,PLAN,p))
    def test_noop_allowed(self):
        p=copy.deepcopy(PLAN);p["resource_changes"][0]["change"]["actions"]=["no-op"];self.assertEqual(validate(SAFE,p,POLICY),[])
if __name__=="__main__":unittest.main()
