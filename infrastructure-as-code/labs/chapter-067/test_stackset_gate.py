import copy,json,unittest
from pathlib import Path
from stackset_gate import validate
ROOT=Path(__file__).parent
PARENT=json.loads((ROOT/"parent-template.json").read_text())
CHILD=json.loads((ROOT/"child-template.json").read_text())
SAFE=json.loads((ROOT/"fixtures/safe.json").read_text())
UNSAFE=json.loads((ROOT/"fixtures/unsafe.json").read_text())
POLICY=json.loads((ROOT/"policy.json").read_text())
class StackSetGateTests(unittest.TestCase):
    def bad(self,fn):
        m=copy.deepcopy(SAFE);fn(m);self.assertTrue(validate(PARENT,CHILD,m,POLICY))
    def test_safe(self):self.assertEqual(validate(PARENT,CHILD,SAFE,POLICY),[])
    def test_unsafe(self):self.assertTrue(validate(PARENT,CHILD,UNSAFE,POLICY))
    def test_environment(self):self.bad(lambda m:m.update(environment='prod'))
    def test_account(self):self.bad(lambda m:m.update(account='prod'))
    def test_region(self):self.bad(lambda m:m.update(region='eu-west-1'))
    def test_ou(self):self.bad(lambda m:m.update(ou='production'))
    def test_stackset_name(self):self.bad(lambda m:m.update(stackset='prod-stackset'))
    def test_owner(self):self.bad(lambda m:m.update(owner=''))
    def test_ticket(self):self.bad(lambda m:m.update(change_ticket=''))
    def test_labels(self):self.bad(lambda m:m.pop('labels'))
    def test_label_environment(self):self.bad(lambda m:m['labels'].update(environment='prod'))
    def test_label_owner(self):self.bad(lambda m:m['labels'].update(owner='other'))
    def test_label_manager(self):self.bad(lambda m:m['labels'].update(**{'managed-by':'manual'}))
    def test_template_parent_contract_validated(self):self.bad(lambda m:m['template'].update(parent_contract_validated=False))
    def test_template_child_contract_validated(self):self.bad(lambda m:m['template'].update(child_contract_validated=False))
    def test_template_immutable_artifacts(self):self.bad(lambda m:m['template'].update(immutable_artifacts=False))
    def test_template_parameter_contracts_reviewed(self):self.bad(lambda m:m['template'].update(parameter_contracts_reviewed=False))
    def test_template_exports_reviewed(self):self.bad(lambda m:m['template'].update(exports_reviewed=False))
    def test_template_no_embedded_secrets(self):self.bad(lambda m:m['template'].update(no_embedded_secrets=False))
    def test_missing_template(self):self.bad(lambda m:m.pop('template'))
    def test_stackset_account_allowlisted(self):self.bad(lambda m:m['stackset'].update(account_allowlisted=False))
    def test_stackset_region_allowlisted(self):self.bad(lambda m:m['stackset'].update(region_allowlisted=False))
    def test_stackset_ou_scope_reviewed(self):self.bad(lambda m:m['stackset'].update(ou_scope_reviewed=False))
    def test_stackset_permission_model_reviewed(self):self.bad(lambda m:m['stackset'].update(permission_model_reviewed=False))
    def test_stackset_concurrency_bounded(self):self.bad(lambda m:m['stackset'].update(concurrency_bounded=False))
    def test_stackset_failure_tolerance_zero(self):self.bad(lambda m:m['stackset'].update(failure_tolerance_zero=False))
    def test_stackset_target_matrix_signed(self):self.bad(lambda m:m['stackset'].update(target_matrix_signed=False))
    def test_missing_stackset(self):self.bad(lambda m:m.pop('stackset'))
    def test_security_least_privilege(self):self.bad(lambda m:m['security'].update(least_privilege=False))
    def test_security_execution_role_scoped(self):self.bad(lambda m:m['security'].update(execution_role_scoped=False))
    def test_security_no_plaintext_secrets(self):self.bad(lambda m:m['security'].update(no_plaintext_secrets=False))
    def test_security_cloudtrail_enabled(self):self.bad(lambda m:m['security'].update(cloudtrail_enabled=False))
    def test_security_provenance_verified(self):self.bad(lambda m:m['security'].update(provenance_verified=False))
    def test_security_change_approved(self):self.bad(lambda m:m['security'].update(change_approved=False))
    def test_missing_security(self):self.bad(lambda m:m.pop('security'))
    def test_operations_dbre_approved(self):self.bad(lambda m:m['operations'].update(dbre_approved=False))
    def test_operations_backup_verified(self):self.bad(lambda m:m['operations'].update(backup_verified=False))
    def test_operations_rollback_documented(self):self.bad(lambda m:m['operations'].update(rollback_documented=False))
    def test_operations_drift_reviewed(self):self.bad(lambda m:m['operations'].update(drift_reviewed=False))
    def test_operations_slo_reviewed(self):self.bad(lambda m:m['operations'].update(slo_reviewed=False))
    def test_operations_restore_tested(self):self.bad(lambda m:m['operations'].update(restore_tested=False))
    def test_missing_operations(self):self.bad(lambda m:m.pop('operations'))
    def test_destructive(self):self.bad(lambda m:m['stackset'].update(destructive_operation=True))
    def test_bad_parent_version(self):
        p=copy.deepcopy(PARENT);p["AWSTemplateFormatVersion"]="wrong";self.assertTrue(validate(p,CHILD,SAFE,POLICY))
    def test_bad_child_version(self):
        c=copy.deepcopy(CHILD);c["AWSTemplateFormatVersion"]="wrong";self.assertTrue(validate(PARENT,c,SAFE,POLICY))
    def test_bad_child_url(self):
        p=copy.deepcopy(PARENT);p["Resources"]["NestedDemo"]["Properties"]["TemplateURL"]="https://evil.invalid/template";self.assertTrue(validate(p,CHILD,SAFE,POLICY))
    def test_bad_child_output(self):
        c=copy.deepcopy(CHILD);c["Outputs"].pop("Environment");self.assertTrue(validate(PARENT,c,SAFE,POLICY))
    def test_invalid_manifest(self):self.assertTrue(validate(PARENT,CHILD,[],POLICY))
    def test_invalid_policy(self):self.assertTrue(validate(PARENT,CHILD,SAFE,[]))
    def test_fail_open_policy(self):
        p=copy.deepcopy(POLICY);p["deny_prod_targets"]=False;self.assertTrue(validate(PARENT,CHILD,SAFE,p))
    def test_missing_controls(self):
        p=copy.deepcopy(POLICY);p.pop("required_controls");self.assertTrue(validate(PARENT,CHILD,SAFE,p))
if __name__=="__main__":unittest.main()
