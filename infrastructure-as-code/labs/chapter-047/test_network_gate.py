import copy,json,unittest
from pathlib import Path
from network_gate import validate
ROOT=Path(__file__).parent
SAFE=json.loads((ROOT/"fixtures/network-safe.json").read_text())
UNSAFE=json.loads((ROOT/"fixtures/network-unsafe.json").read_text())
PLAN=json.loads((ROOT/"fixtures/plan-safe.json").read_text())
DESTRUCTIVE=json.loads((ROOT/"fixtures/plan-destructive.json").read_text())
POLICY=json.loads((ROOT/"network-policy.json").read_text())
class NetworkGateTests(unittest.TestCase):
    def bad(self,fn):
        m=copy.deepcopy(SAFE);fn(m);self.assertTrue(validate(m,PLAN,POLICY))
    def bad_plan(self,fn):
        p=copy.deepcopy(PLAN);fn(p);self.assertTrue(validate(SAFE,p,POLICY))
    def test_safe(self):self.assertEqual(validate(SAFE,PLAN,POLICY),[])
    def test_unsafe(self):self.assertTrue(validate(UNSAFE,DESTRUCTIVE,POLICY))
    def test_destructive(self):self.assertTrue(validate(SAFE,DESTRUCTIVE,POLICY))
    def test_environment(self):self.bad(lambda m:m.update(environment='invalid'))
    def test_project_id(self):self.bad(lambda m:m.update(project_id='INVALID'))
    def test_region(self):self.bad(lambda m:m.update(region='europe-west1'))
    def test_owner(self):self.bad(lambda m:m.update(owner=''))
    def test_ticket(self):self.bad(lambda m:m.update(change_ticket=''))
    def test_state_namespace(self):self.bad(lambda m:m.update(state_namespace='iac-dev'))
    def test_vpc_custom_mode(self):self.bad(lambda m:m['vpc'].update(custom_mode=False))
    def test_vpc_shared_vpc_reviewed(self):self.bad(lambda m:m['vpc'].update(shared_vpc_reviewed=False))
    def test_vpc_private_google_access(self):self.bad(lambda m:m['vpc'].update(private_google_access=False))
    def test_vpc_secondary_ranges_reviewed(self):self.bad(lambda m:m['vpc'].update(secondary_ranges_reviewed=False))
    def test_no_vpc(self):self.bad(lambda m:m.pop('vpc'))
    def test_firewall_restricted(self):self.bad(lambda m:m['firewall'].update(restricted=False))
    def test_firewall_logging(self):self.bad(lambda m:m['firewall'].update(logging=False))
    def test_firewall_least_privilege_targets(self):self.bad(lambda m:m['firewall'].update(least_privilege_targets=False))
    def test_firewall_hierarchical_policy_reviewed(self):self.bad(lambda m:m['firewall'].update(hierarchical_policy_reviewed=False))
    def test_no_firewall(self):self.bad(lambda m:m.pop('firewall'))
    def test_connectivity_cloud_nat_enabled(self):self.bad(lambda m:m['connectivity'].update(cloud_nat_enabled=False))
    def test_connectivity_nat_capacity_reviewed(self):self.bad(lambda m:m['connectivity'].update(nat_capacity_reviewed=False))
    def test_connectivity_private_service_connect_reviewed(self):self.bad(lambda m:m['connectivity'].update(private_service_connect_reviewed=False))
    def test_connectivity_cloud_dns_reviewed(self):self.bad(lambda m:m['connectivity'].update(cloud_dns_reviewed=False))
    def test_connectivity_hybrid_routes_reviewed(self):self.bad(lambda m:m['connectivity'].update(hybrid_routes_reviewed=False))
    def test_connectivity_peering_nontransitive_reviewed(self):self.bad(lambda m:m['connectivity'].update(peering_nontransitive_reviewed=False))
    def test_no_connectivity(self):self.bad(lambda m:m.pop('connectivity'))
    def test_audit_vpc_flow_logs_enabled(self):self.bad(lambda m:m['audit'].update(vpc_flow_logs_enabled=False))
    def test_audit_monitoring_enabled(self):self.bad(lambda m:m['audit'].update(monitoring_enabled=False))
    def test_audit_dbre_approved(self):self.bad(lambda m:m['audit'].update(dbre_approved=False))
    def test_audit_security_approved(self):self.bad(lambda m:m['audit'].update(security_approved=False))
    def test_audit_change_approved(self):self.bad(lambda m:m['audit'].update(change_approved=False))
    def test_no_audit(self):self.bad(lambda m:m.pop('audit'))
    def test_public_ssh(self):self.bad(lambda m:m['firewall'].update(public_ssh_ingress=True))
    def test_public_db(self):self.bad(lambda m:m['firewall'].update(public_database_ingress=True))
    def test_subnet_invalid(self):self.bad(lambda m:m['vpc'].update(subnet_cidr='not-a-cidr'))
    def test_pod_invalid(self):self.bad(lambda m:m['vpc'].update(pod_cidr='0.0.0.0/0'))
    def test_services_invalid(self):self.bad(lambda m:m['vpc'].update(services_cidr='not-a-cidr'))
    def test_cidr_overlap(self):self.bad(lambda m:m['vpc'].update(pod_cidr='10.84.0.0/16'))
    def test_cidr_overlap_services(self):self.bad(lambda m:m['vpc'].update(services_cidr='10.88.0.0/20'))
    def test_environment_label(self):self.bad(lambda m:m['labels'].update(environment='dev'))
    def test_owner_label(self):self.bad(lambda m:m['labels'].update(owner=''))
    def test_managedby_label(self):self.bad(lambda m:m['labels'].update(**{'managed-by':'manual'}))
    def test_no_labels(self):self.bad(lambda m:m.pop('labels'))
    def test_delete(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["delete"]))
    def test_replace(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["create","delete"]))
    def test_invalid_action(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["destroy"]))
    def test_unapproved_type(self):self.bad_plan(lambda p:p["resource_changes"][0].update(type="google_compute_network"))
    def test_missing_plan(self):self.assertTrue(validate(SAFE,{},POLICY))
    def test_invalid_manifest(self):self.assertTrue(validate([],PLAN,POLICY))
    def test_fail_open_policy(self):
        p=copy.deepcopy(POLICY);p["deny_destructive_actions"]=False;self.assertTrue(validate(SAFE,PLAN,p))
    def test_noop_allowed(self):
        p=copy.deepcopy(PLAN);p["resource_changes"][0]["change"]["actions"]=["no-op"];self.assertEqual(validate(SAFE,p,POLICY),[])
if __name__=="__main__":unittest.main()
