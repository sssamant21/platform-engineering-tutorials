import copy,json,unittest
from pathlib import Path
from aws_foundation_gate import validate
ROOT=Path(__file__).parent
SAFE=json.loads((ROOT/"fixtures/foundation-safe.json").read_text())
UNSAFE=json.loads((ROOT/"fixtures/foundation-unsafe.json").read_text())
PLAN=json.loads((ROOT/"fixtures/plan-safe.json").read_text())
DESTRUCTIVE=json.loads((ROOT/"fixtures/plan-destructive.json").read_text())
POLICY=json.loads((ROOT/"aws-foundation-policy.json").read_text())
class AwsFoundationTests(unittest.TestCase):
    def bad(self,fn):
        m=copy.deepcopy(SAFE);fn(m);self.assertTrue(validate(m,PLAN,POLICY))
    def bad_plan(self,fn):
        p=copy.deepcopy(PLAN);fn(p);self.assertTrue(validate(SAFE,p,POLICY))
    def test_safe(self):self.assertEqual(validate(SAFE,PLAN,POLICY),[])
    def test_unsafe(self):self.assertTrue(validate(UNSAFE,DESTRUCTIVE,POLICY))
    def test_destructive(self):self.assertTrue(validate(SAFE,DESTRUCTIVE,POLICY))
    def test_environment(self):self.bad(lambda m:m.update(environment="invalid"))
    def test_account_short(self):self.bad(lambda m:m.update(aws_account_id="123"))
    def test_account_non_numeric(self):self.bad(lambda m:m.update(aws_account_id="a"*12))
    def test_primary_region(self):self.bad(lambda m:m.update(primary_region="eu-central-1"))
    def test_dr_region(self):self.bad(lambda m:m.update(dr_region="eu-central-1"))
    def test_same_region(self):self.bad(lambda m:m.update(dr_region="us-east-1"))
    def test_owner(self):self.bad(lambda m:m.update(owner=""))
    def test_cost_center(self):self.bad(lambda m:m.update(cost_center=""))
    def test_ticket(self):self.bad(lambda m:m.update(change_ticket=""))
    def test_state_namespace(self):self.bad(lambda m:m.update(state_namespace="iac-dev"))
    def test_environment_tag(self):self.bad(lambda m:m["tags"].update(Environment="dev"))
    def test_owner_tag(self):self.bad(lambda m:m["tags"].update(Owner=""))
    def test_cost_tag(self):self.bad(lambda m:m["tags"].update(CostCenter=""))
    def test_managedby_tag(self):self.bad(lambda m:m["tags"].update(ManagedBy="manual"))
    def test_no_tags(self):self.bad(lambda m:m.pop("tags"))
    def test_short_lived(self):self.bad(lambda m:m["identity"].update(short_lived_credentials=False))
    def test_oidc(self):self.bad(lambda m:m["identity"].update(oidc_federation=False))
    def test_least_privilege(self):self.bad(lambda m:m["identity"].update(least_privilege_reviewed=False))
    def test_no_identity(self):self.bad(lambda m:m.pop("identity"))
    def test_backend_type(self):self.bad(lambda m:m["backend"].update(type="local"))
    def test_backend_encryption(self):self.bad(lambda m:m["backend"].update(encrypted=False))
    def test_backend_versioning(self):self.bad(lambda m:m["backend"].update(versioning=False))
    def test_backend_lockfile(self):self.bad(lambda m:m["backend"].update(lockfile=False))
    def test_backend_public_access(self):self.bad(lambda m:m["backend"].update(public_access_blocked=False))
    def test_no_backend(self):self.bad(lambda m:m.pop("backend"))
    def test_prod_replicas(self):self.bad(lambda m:m["database"].update(replicas=1))
    def test_prod_bool_replicas(self):self.bad(lambda m:m["database"].update(replicas=True))
    def test_prod_backup(self):self.bad(lambda m:m["database"].update(backup_enabled=False))
    def test_prod_encryption(self):self.bad(lambda m:m["database"].update(encryption_enabled=False))
    def test_prod_multi_az(self):self.bad(lambda m:m["database"].update(multi_az_enabled=False))
    def test_no_database(self):self.bad(lambda m:m.pop("database"))
    def test_delete(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["delete"]))
    def test_replace(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["create","delete"]))
    def test_bad_action(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["destroy"]))
    def test_unapproved_type(self):self.bad_plan(lambda p:p["resource_changes"][0].update(type="aws_db_instance"))
    def test_missing_plan(self):self.assertTrue(validate(SAFE,{},POLICY))
    def test_bad_manifest(self):self.assertTrue(validate([],PLAN,POLICY))
    def test_fail_open_policy(self):
        p=copy.deepcopy(POLICY);p["deny_destructive_actions"]=False;self.assertTrue(validate(SAFE,PLAN,p))
    def test_noop_allowed(self):
        p=copy.deepcopy(PLAN);p["resource_changes"][0]["change"]["actions"]=["no-op"];self.assertEqual(validate(SAFE,p,POLICY),[])
if __name__=="__main__":unittest.main()
