import copy,json,unittest
from pathlib import Path
from ansible_gate import validate
ROOT=Path(__file__).parent
SAFE=json.loads((ROOT/"fixtures/safe.json").read_text())
UNSAFE=json.loads((ROOT/"fixtures/unsafe.json").read_text())
POLICY=json.loads((ROOT/"policy.json").read_text())
class AnsibleGateTests(unittest.TestCase):
    def bad(self,fn):
        m=copy.deepcopy(SAFE);fn(m);self.assertTrue(validate(m,POLICY))
    def test_safe(self):self.assertEqual(validate(SAFE,POLICY),[])
    def test_unsafe(self):self.assertTrue(validate(UNSAFE,POLICY))
    def test_environment(self):self.bad(lambda m:m.update(environment='prod'))
    def test_inventory_name(self):self.bad(lambda m:m.update(inventory='prod.ini'))
    def test_targets(self):self.bad(lambda m:m.update(target_hosts=['db-prod-01']))
    def test_connection(self):self.bad(lambda m:m.update(connection='ssh'))
    def test_owner(self):self.bad(lambda m:m.update(owner=''))
    def test_ticket(self):self.bad(lambda m:m.update(change_ticket=''))
    def test_labels(self):self.bad(lambda m:m.pop('labels'))
    def test_label_environment(self):self.bad(lambda m:m['labels'].update(environment='prod'))
    def test_label_owner(self):self.bad(lambda m:m['labels'].update(owner='other'))
    def test_label_manager(self):self.bad(lambda m:m['labels'].update(**{'managed-by':'manual'}))
    def test_inventory_localhost_only(self):self.bad(lambda m:m['inventory'].update(localhost_only=False))
    def test_inventory_inventory_reviewed(self):self.bad(lambda m:m['inventory'].update(inventory_reviewed=False))
    def test_inventory_limit_verified(self):self.bad(lambda m:m['inventory'].update(limit_verified=False))
    def test_inventory_no_prod_hosts(self):self.bad(lambda m:m['inventory'].update(no_prod_hosts=False))
    def test_inventory_host_group_ownership(self):self.bad(lambda m:m['inventory'].update(host_group_ownership=False))
    def test_inventory_connection_local(self):self.bad(lambda m:m['inventory'].update(connection_local=False))
    def test_missing_inventory(self):self.bad(lambda m:m.pop('inventory'))
    def test_configuration_modules_fqcn(self):self.bad(lambda m:m['configuration'].update(modules_fqcn=False))
    def test_configuration_idempotence_verified(self):self.bad(lambda m:m['configuration'].update(idempotence_verified=False))
    def test_configuration_check_mode_reviewed(self):self.bad(lambda m:m['configuration'].update(check_mode_reviewed=False))
    def test_configuration_template_reviewed(self):self.bad(lambda m:m['configuration'].update(template_reviewed=False))
    def test_configuration_variables_validated(self):self.bad(lambda m:m['configuration'].update(variables_validated=False))
    def test_configuration_handlers_change_only(self):self.bad(lambda m:m['configuration'].update(handlers_change_only=False))
    def test_missing_configuration(self):self.bad(lambda m:m.pop('configuration'))
    def test_security_least_privilege(self):self.bad(lambda m:m['security'].update(least_privilege=False))
    def test_security_become_disabled_lab(self):self.bad(lambda m:m['security'].update(become_disabled_lab=False))
    def test_security_secrets_not_plaintext(self):self.bad(lambda m:m['security'].update(secrets_not_plaintext=False))
    def test_security_diff_no_secrets(self):self.bad(lambda m:m['security'].update(diff_no_secrets=False))
    def test_security_collections_pinned(self):self.bad(lambda m:m['security'].update(collections_pinned=False))
    def test_security_change_approved(self):self.bad(lambda m:m['security'].update(change_approved=False))
    def test_missing_security(self):self.bad(lambda m:m.pop('security'))
    def test_operations_slo_reviewed(self):self.bad(lambda m:m['operations'].update(slo_reviewed=False))
    def test_operations_dbre_approved(self):self.bad(lambda m:m['operations'].update(dbre_approved=False))
    def test_operations_backup_verified(self):self.bad(lambda m:m['operations'].update(backup_verified=False))
    def test_operations_rollback_documented(self):self.bad(lambda m:m['operations'].update(rollback_documented=False))
    def test_operations_serial_rollout(self):self.bad(lambda m:m['operations'].update(serial_rollout=False))
    def test_missing_operations(self):self.bad(lambda m:m.pop('operations'))
    def test_unapproved_restart(self):self.bad(lambda m:m['operations'].update(unapproved_restart=True))
    def test_invalid_manifest(self):self.assertTrue(validate([],POLICY))
    def test_invalid_policy(self):self.assertTrue(validate(SAFE,[]))
    def test_fail_open(self):
        p=copy.deepcopy(POLICY);p["deny_prod_targets"]=False;self.assertTrue(validate(SAFE,p))
    def test_missing_controls_policy(self):
        p=copy.deepcopy(POLICY);p.pop("required_controls");self.assertTrue(validate(SAFE,p))
if __name__=="__main__":unittest.main()
