import copy,json,unittest
from pathlib import Path
from gate import validate
P=Path(__file__).parent
SAFE=json.loads((P/'fixtures/safe.json').read_text())
POLICY=json.loads((P/'policy.json').read_text())
class GateTests(unittest.TestCase):
    def bad(self,mutator):
        e=copy.deepcopy(SAFE);mutator(e);self.assertTrue(validate(e,POLICY))
    def test_safe(self):self.assertEqual(validate(SAFE,POLICY),[])
    def test_unsafe(self):self.assertTrue(validate(json.loads((P/'fixtures/unsafe.json').read_text()),POLICY))
    def test_invalid_evidence(self):self.assertTrue(validate([],POLICY))
    def test_invalid_policy(self):self.assertTrue(validate(SAFE,[]))
    def test_bad_policy_schema(self):
        p=copy.deepcopy(POLICY);p['schema_version']=2;self.assertTrue(validate(SAFE,p))
    def test_bad_policy_required(self):
        p=copy.deepcopy(POLICY);p['required_controls']=[];self.assertTrue(validate(SAFE,p))
    def test_bad_policy_duplicate(self):
        p=copy.deepcopy(POLICY);p['required_controls']+=p['required_controls'][:1];self.assertTrue(validate(SAFE,p))
    def test_bad_policy_flag(self):
        p=copy.deepcopy(POLICY);p['require_exact_controls']=False;self.assertTrue(validate(SAFE,p))
    def test_missing_ticket(self):self.bad(lambda e:e.pop('ticket'))
    def test_bad_ticket(self):self.bad(lambda e:e.update(ticket='APPROVED'))
