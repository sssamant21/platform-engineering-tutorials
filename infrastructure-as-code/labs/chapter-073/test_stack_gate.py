    def bad(self,fn):
        m=copy.deepcopy(SAFE);fn(m);self.assertTrue(validate(m,POLICY))
    def test_safe(self):self.assertEqual(validate(SAFE,POLICY),[])
    def test_unsafe(self):self.assertTrue(validate(UNSAFE,POLICY))
    def test_environment(self):self.bad(lambda m:m.update(environment='prod'))
    def test_stack(self):self.bad(lambda m:m.update(stack='prod'))
    def test_project(self):self.bad(lambda m:m.update(project='wrong'))
    def test_backend(self):self.bad(lambda m:m.update(backend='s3://production'))
    def test_provider_target(self):self.bad(lambda m:m.update(provider_target='production'))
    def test_owner(self):self.bad(lambda m:m.update(owner=''))
    def test_ticket(self):self.bad(lambda m:m.update(change_ticket=''))
    def test_labels(self):self.bad(lambda m:m.pop('labels'))
    def test_label_environment(self):self.bad(lambda m:m['labels'].update(environment='prod'))
    def test_label_owner(self):self.bad(lambda m:m['labels'].update(owner='other'))
    def test_label_manager(self):self.bad(lambda m:m['labels'].update(**{'managed-by':'manual'}))
    def test_architecture_project_reviewed(self):self.bad(lambda m:m['architecture'].update(project_reviewed=False))
    def test_architecture_stack_identity_verified(self):self.bad(lambda m:m['architecture'].update(stack_identity_verified=False))
    def test_architecture_backend_identity_verified(self):self.bad(lambda m:m['architecture'].update(backend_identity_verified=False))
    def test_architecture_owner_verified(self):self.bad(lambda m:m['architecture'].update(owner_verified=False))
    def test_architecture_provider_target_verified(self):self.bad(lambda m:m['architecture'].update(provider_target_verified=False))
    def test_missing_architecture(self):self.bad(lambda m:m.pop('architecture'))
    def test_secrets_encryption_enabled(self):self.bad(lambda m:m['secrets'].update(encryption_enabled=False))
    def test_secrets_secret_provider_reviewed(self):self.bad(lambda m:m['secrets'].update(secret_provider_reviewed=False))
    def test_secrets_plaintext_secrets_denied(self):self.bad(lambda m:m['secrets'].update(plaintext_secrets_denied=False))
    def test_secrets_key_recovery_reviewed(self):self.bad(lambda m:m['secrets'].update(key_recovery_reviewed=False))
    def test_secrets_log_redaction_reviewed(self):self.bad(lambda m:m['secrets'].update(log_redaction_reviewed=False))
    def test_missing_secrets(self):self.bad(lambda m:m.pop('secrets'))
    def test_state_checkpoint_backup_verified(self):self.bad(lambda m:m['state'].update(checkpoint_backup_verified=False))
    def test_state_backend_access_scoped(self):self.bad(lambda m:m['state'].update(backend_access_scoped=False))
    def test_state_concurrency_controlled(self):self.bad(lambda m:m['state'].update(concurrency_controlled=False))
    def test_state_restore_rehearsed(self):self.bad(lambda m:m['state'].update(restore_rehearsed=False))
    def test_state_state_import_approved(self):self.bad(lambda m:m['state'].update(state_import_approved=False))
    def test_missing_state(self):self.bad(lambda m:m.pop('state'))
    def test_operations_preview_reviewed(self):self.bad(lambda m:m['operations'].update(preview_reviewed=False))
    def test_operations_refresh_reviewed(self):self.bad(lambda m:m['operations'].update(refresh_reviewed=False))
    def test_operations_drift_reviewed(self):self.bad(lambda m:m['operations'].update(drift_reviewed=False))
