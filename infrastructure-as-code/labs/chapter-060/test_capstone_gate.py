    def test_delivery_immutable_artifacts(self):self.bad(lambda m:m['delivery'].update(immutable_artifacts=False))
    def test_delivery_environment_approvals(self):self.bad(lambda m:m['delivery'].update(environment_approvals=False))
    def test_no_delivery(self):self.bad(lambda m:m.pop('delivery'))
