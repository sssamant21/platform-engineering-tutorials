    def test_migration_rollback_documented(self):self.bad(lambda m:m['migration'].update(rollback_documented=False))
    def test_no_migration(self):self.bad(lambda m:m.pop('migration'))
    def test_state_backend_keys_unique(self):self.bad(lambda m:m['state'].update(backend_keys_unique=False))
    def test_state_backend_encrypted(self):self.bad(lambda m:m['state'].update(backend_encrypted=False))
    def test_state_backend_lock_verified(self):self.bad(lambda m:m['state'].update(backend_lock_verified=False))
    def test_state_lineage_serial_recorded(self):self.bad(lambda m:m['state'].update(lineage_serial_recorded=False))
    def test_state_state_backup_verified(self):self.bad(lambda m:m['state'].update(state_backup_verified=False))
    def test_state_isolated_restore_tested(self):self.bad(lambda m:m['state'].update(isolated_restore_tested=False))
    def test_state_exclusive_writer(self):self.bad(lambda m:m['state'].update(exclusive_writer=False))
    def test_no_state(self):self.bad(lambda m:m.pop('state'))
    def test_graph_dag_acyclic(self):self.bad(lambda m:m['graph'].update(dag_acyclic=False))
    def test_graph_dependency_outputs_reviewed(self):self.bad(lambda m:m['graph'].update(dependency_outputs_reviewed=False))
    def test_graph_prod_mock_outputs_disabled(self):self.bad(lambda m:m['graph'].update(prod_mock_outputs_disabled=False))
    def test_graph_bounded_parallelism(self):self.bad(lambda m:m['graph'].update(bounded_parallelism=False))
    def test_graph_partial_failure_runbook(self):self.bad(lambda m:m['graph'].update(partial_failure_runbook=False))
    def test_graph_gitops_single_writer(self):self.bad(lambda m:m['graph'].update(gitops_single_writer=False))
    def test_no_graph(self):self.bad(lambda m:m.pop('graph'))
