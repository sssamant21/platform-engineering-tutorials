import copy,json,unittest
from pathlib import Path
from compute_gate import validate
ROOT=Path(__file__).parent
SAFE=json.loads((ROOT/"fixtures/compute-safe.json").read_text())
UNSAFE=json.loads((ROOT/"fixtures/compute-unsafe.json").read_text())
PLAN=json.loads((ROOT/"fixtures/plan-safe.json").read_text())
DESTRUCTIVE=json.loads((ROOT/"fixtures/plan-destructive.json").read_text())
POLICY=json.loads((ROOT/"compute-policy.json").read_text())
class ComputeGateTests(unittest.TestCase):
    def bad(self,fn):
        m=copy.deepcopy(SAFE);fn(m);self.assertTrue(validate(m,PLAN,POLICY))
    def bad_plan(self,fn):
        p=copy.deepcopy(PLAN);fn(p);self.assertTrue(validate(SAFE,p,POLICY))
    def test_safe(self):self.assertEqual(validate(SAFE,PLAN,POLICY),[])
    def test_unsafe(self):self.assertTrue(validate(UNSAFE,DESTRUCTIVE,POLICY))
    def test_destructive(self):self.assertTrue(validate(SAFE,DESTRUCTIVE,POLICY))
    def test_environment(self):self.bad(lambda m:m.update(environment='invalid'))
    def test_subscription(self):self.bad(lambda m:m.update(subscription_id='invalid'))
    def test_location(self):self.bad(lambda m:m.update(location='westeurope'))
    def test_owner(self):self.bad(lambda m:m.update(owner=''))
    def test_ticket(self):self.bad(lambda m:m.update(change_ticket=''))
    def test_state_namespace(self):self.bad(lambda m:m.update(state_namespace='iac-dev'))
    def test_sku(self):self.bad(lambda m:m['compute'].update(vm_sku='Standard_B1s'))
    def test_node_count(self):self.bad(lambda m:m['compute'].update(node_count=1))
    def test_node_count_float(self):self.bad(lambda m:m['compute'].update(node_count=3.5))
    def test_zones(self):self.bad(lambda m:m['compute'].update(availability_zones=['1']))
    def test_zones_invalid(self):self.bad(lambda m:m['compute'].update(availability_zones=['1','4']))
    def test_health_probe(self):self.bad(lambda m:m['compute'].update(vmss_health_probes=False))
    def test_upgrade(self):self.bad(lambda m:m['compute'].update(upgrade_reviewed=False))
    def test_no_compute(self):self.bad(lambda m:m.pop('compute'))
    def test_private_cluster(self):self.bad(lambda m:m['aks'].update(private_cluster=False))
    def test_oidc_issuer_enabled(self):self.bad(lambda m:m['aks'].update(oidc_issuer_enabled=False))
    def test_workload_identity_enabled(self):self.bad(lambda m:m['aks'].update(workload_identity_enabled=False))
    def test_kubernetes_version_reviewed(self):self.bad(lambda m:m['aks'].update(kubernetes_version_reviewed=False))
    def test_system_pool_dedicated(self):self.bad(lambda m:m['aks'].update(system_pool_dedicated=False))
    def test_autoscaler_enabled(self):self.bad(lambda m:m['aks'].update(autoscaler_enabled=False))
    def test_network_model_reviewed(self):self.bad(lambda m:m['aks'].update(network_model_reviewed=False))
    def test_no_aks(self):self.bad(lambda m:m.pop('aks'))
    def test_image_digest_pinned(self):self.bad(lambda m:m['application'].update(image_digest_pinned=False))
    def test_acr_private(self):self.bad(lambda m:m['application'].update(acr_private=False))
    def test_acr_identity_reviewed(self):self.bad(lambda m:m['application'].update(acr_identity_reviewed=False))
    def test_pdb_enabled(self):self.bad(lambda m:m['application'].update(pdb_enabled=False))
    def test_private_database_access(self):self.bad(lambda m:m['application'].update(private_database_access=False))
    def test_ingress_tls_enabled(self):self.bad(lambda m:m['application'].update(ingress_tls_enabled=False))
    def test_replicas(self):self.bad(lambda m:m['application'].update(replicas=1))
    def test_replicas_float(self):self.bad(lambda m:m['application'].update(replicas=3.5))
    def test_no_application(self):self.bad(lambda m:m.pop('application'))
    def test_diagnostics_enabled(self):self.bad(lambda m:m['audit'].update(diagnostics_enabled=False))
    def test_alerting_enabled(self):self.bad(lambda m:m['audit'].update(alerting_enabled=False))
    def test_slo_reviewed(self):self.bad(lambda m:m['audit'].update(slo_reviewed=False))
    def test_dbre_connection_tested(self):self.bad(lambda m:m['audit'].update(dbre_connection_tested=False))
    def test_rollback_drill_passed(self):self.bad(lambda m:m['audit'].update(rollback_drill_passed=False))
    def test_no_audit(self):self.bad(lambda m:m.pop('audit'))
    def test_environment_tag(self):self.bad(lambda m:m['tags'].update(Environment='dev'))
    def test_owner_tag(self):self.bad(lambda m:m['tags'].update(Owner=''))
    def test_managedby_tag(self):self.bad(lambda m:m['tags'].update(ManagedBy='manual'))
    def test_no_tags(self):self.bad(lambda m:m.pop('tags'))
    def test_delete(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["delete"]))
    def test_replace(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["create","delete"]))
    def test_invalid_action(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["destroy"]))
    def test_unapproved_type(self):self.bad_plan(lambda p:p["resource_changes"][0].update(type="azurerm_kubernetes_cluster"))
    def test_missing_plan(self):self.assertTrue(validate(SAFE,{},POLICY))
    def test_invalid_manifest(self):self.assertTrue(validate([],PLAN,POLICY))
    def test_fail_open_policy(self):
        p=copy.deepcopy(POLICY);p["deny_destructive_actions"]=False;self.assertTrue(validate(SAFE,PLAN,p))
    def test_noop_allowed(self):
        p=copy.deepcopy(PLAN);p["resource_changes"][0]["change"]["actions"]=["no-op"];self.assertEqual(validate(SAFE,p,POLICY),[])
if __name__=="__main__":unittest.main()
