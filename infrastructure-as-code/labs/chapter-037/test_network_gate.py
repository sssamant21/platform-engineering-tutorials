import copy,json,unittest
from pathlib import Path
from network_gate import validate
ROOT=Path(__file__).parent
SAFE=json.loads((ROOT/"fixtures/network-safe.json").read_text())
UNSAFE=json.loads((ROOT/"fixtures/network-unsafe.json").read_text())
PLAN=json.loads((ROOT/"fixtures/plan-safe.json").read_text())
DESTRUCTIVE=json.loads((ROOT/"fixtures/plan-destructive.json").read_text())
POLICY=json.loads((ROOT/"network-policy.json").read_text())
class NetworkGateTests(unittest.TestCase):
    def bad(self,fn):
        m=copy.deepcopy(SAFE);fn(m);self.assertTrue(validate(m,PLAN,POLICY))
    def bad_plan(self,fn):
        p=copy.deepcopy(PLAN);fn(p);self.assertTrue(validate(SAFE,p,POLICY))
    def test_safe(self):self.assertEqual(validate(SAFE,PLAN,POLICY),[])
    def test_unsafe(self):self.assertTrue(validate(UNSAFE,DESTRUCTIVE,POLICY))
    def test_destructive(self):self.assertTrue(validate(SAFE,DESTRUCTIVE,POLICY))
    def test_environment(self):self.bad(lambda m:m.update(environment="invalid"))
    def test_owner(self):self.bad(lambda m:m.update(owner=""))
    def test_ticket(self):self.bad(lambda m:m.update(change_ticket=""))
    def test_state_namespace(self):self.bad(lambda m:m.update(state_namespace="iac-dev-network"))
    def test_vpc_cidr(self):self.bad(lambda m:m.update(vpc_cidr="bad"))
    def test_vpc_noncanonical(self):self.bad(lambda m:m.update(vpc_cidr="10.90.1.0/16"))
    def test_one_az(self):self.bad(lambda m:m.update(availability_zones=["us-east-1a"]))
    def test_duplicate_az(self):self.bad(lambda m:m.update(availability_zones=["us-east-1a","us-east-1a"]))
    def test_missing_subnets(self):self.bad(lambda m:m.update(subnets=[]))
    def test_subnet_overlap(self):self.bad(lambda m:m["subnets"][5].update(cidr="10.90.20.0/24"))
    def test_subnet_outside_vpc(self):self.bad(lambda m:m["subnets"][0].update(cidr="10.100.0.0/24"))
    def test_subnet_bad_cidr(self):self.bad(lambda m:m["subnets"][0].update(cidr="bad"))
    def test_subnet_az(self):self.bad(lambda m:m["subnets"][0].update(az="us-east-1c"))
    def test_subnet_tier(self):self.bad(lambda m:m["subnets"][0].update(tier="untrusted"))
    def test_duplicate_subnet_name(self):self.bad(lambda m:m["subnets"][1].update(name="public_a"))
    def test_missing_db_az(self):self.bad(lambda m:m["subnets"][5].update(az="us-east-1a"))
    def test_missing_public_az(self):self.bad(lambda m:m["subnets"][1].update(az="us-east-1a"))
    def test_public_route(self):self.bad(lambda m:m["routes"].update(public_default="none"))
    def test_app_route(self):self.bad(lambda m:m["routes"].update(application_default="igw"))
    def test_db_route(self):self.bad(lambda m:m["routes"].update(database_default="igw"))
    def test_nat_wrong_az(self):self.bad(lambda m:m["routes"]["nat_by_az"].update({"us-east-1a":"us-east-1b"}))
    def test_nat_missing(self):self.bad(lambda m:m["routes"].update(nat_by_az={}))
    def test_public_db_ingress(self):self.bad(lambda m:m["security"].update(database_public_ingress=True))
    def test_flow_logs(self):self.bad(lambda m:m["security"].update(flow_logs_enabled=False))
    def test_s3_endpoint(self):self.bad(lambda m:m["security"].update(s3_endpoint_enabled=False))
    def test_least_privilege(self):self.bad(lambda m:m["security"].update(least_privilege_reviewed=False))
    def test_no_security(self):self.bad(lambda m:m.pop("security"))
    def test_environment_tag(self):self.bad(lambda m:m["tags"].update(Environment="dev"))
    def test_owner_tag(self):self.bad(lambda m:m["tags"].update(Owner=""))
    def test_managedby_tag(self):self.bad(lambda m:m["tags"].update(ManagedBy="manual"))
    def test_no_tags(self):self.bad(lambda m:m.pop("tags"))
    def test_delete(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["delete"]))
    def test_replace(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["create","delete"]))
    def test_invalid_action(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["destroy"]))
    def test_unapproved_resource(self):self.bad_plan(lambda p:p["resource_changes"][0].update(type="aws_subnet"))
    def test_missing_plan(self):self.assertTrue(validate(SAFE,{},POLICY))
    def test_bad_manifest(self):self.assertTrue(validate([],PLAN,POLICY))
    def test_fail_open_policy(self):
        p=copy.deepcopy(POLICY);p["deny_destructive_actions"]=False;self.assertTrue(validate(SAFE,PLAN,p))
    def test_noop_allowed(self):
        p=copy.deepcopy(PLAN);p["resource_changes"][0]["change"]["actions"]=["no-op"];self.assertEqual(validate(SAFE,p,POLICY),[])
if __name__=="__main__":unittest.main()
