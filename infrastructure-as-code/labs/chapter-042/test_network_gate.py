import copy,json,unittest
from pathlib import Path
from network_gate import validate
ROOT=Path(__file__).parent
SAFE=json.loads((ROOT/"fixtures/network-safe.json").read_text())
UNSAFE=json.loads((ROOT/"fixtures/network-unsafe.json").read_text())
PLAN=json.loads((ROOT/"fixtures/plan-safe.json").read_text())
DESTRUCTIVE=json.loads((ROOT/"fixtures/plan-destructive.json").read_text())
POLICY=json.loads((ROOT/"network-policy.json").read_text())
class NetworkGateTests(unittest.TestCase):
    def bad(self,fn):
        m=copy.deepcopy(SAFE);fn(m);self.assertTrue(validate(m,PLAN,POLICY))
    def bad_plan(self,fn):
        p=copy.deepcopy(PLAN);fn(p);self.assertTrue(validate(SAFE,p,POLICY))
    def test_safe(self):self.assertEqual(validate(SAFE,PLAN,POLICY),[])
    def test_unsafe(self):self.assertTrue(validate(UNSAFE,DESTRUCTIVE,POLICY))
    def test_destructive(self):self.assertTrue(validate(SAFE,DESTRUCTIVE,POLICY))
    def test_environment(self):self.bad(lambda m:m.update(environment="unknown"))
    def test_subscription_id(self):self.bad(lambda m:m.update(subscription_id="invalid"))
    def test_location(self):self.bad(lambda m:m.update(location="westeurope"))
    def test_owner(self):self.bad(lambda m:m.update(owner=""))
    def test_ticket(self):self.bad(lambda m:m.update(change_ticket=""))
    def test_state_namespace(self):self.bad(lambda m:m.update(state_namespace="iac-dev"))
    def test_vnet_invalid(self):self.bad(lambda m:m.update(vnet_cidr="bad"))
    def test_vnet_public(self):self.bad(lambda m:m.update(vnet_cidr="8.8.0.0/16"))
    def test_vnet_noncanonical(self):self.bad(lambda m:m.update(vnet_cidr="10.52.1.0/16"))
    def test_subnet_overlap(self):self.bad(lambda m:m["subnets"].update(app="10.52.0.0/24"))
    def test_subnet_outside(self):self.bad(lambda m:m["subnets"].update(app="10.53.0.0/24"))
    def test_subnet_invalid(self):self.bad(lambda m:m["subnets"].update(app="invalid"))
    def test_subnet_small(self):self.bad(lambda m:m["subnets"].update(app="10.52.7.0/29"))
    def test_subnet_public(self):self.bad(lambda m:m["subnets"].update(app="8.8.8.0/24"))
    def test_subnet_missing(self):self.bad(lambda m:m["subnets"].pop("app"))
    def test_no_subnets(self):self.bad(lambda m:m.pop("subnets"))
    def test_nsg_review(self):self.bad(lambda m:m["security"].update(nsg_reviewed=False))
    def test_management_public(self):self.bad(lambda m:m["security"].update(management_ports_public=True))
    def test_any_any(self):self.bad(lambda m:m["security"].update(allow_any_any_inbound=True))
    def test_udr_review(self):self.bad(lambda m:m["security"].update(udr_reviewed=False))
    def test_next_hop(self):self.bad(lambda m:m["security"].update(forced_tunnel_next_hop_reviewed=False))
    def test_nat_review(self):self.bad(lambda m:m["security"].update(nat_reviewed=False))
    def test_no_security(self):self.bad(lambda m:m.pop("security"))
    def test_private_endpoint(self):self.bad(lambda m:m["private_connectivity"].update(private_endpoint_enabled=False))
    def test_dns_link(self):self.bad(lambda m:m["private_connectivity"].update(private_dns_zone_linked=False))
    def test_dns_resolution(self):self.bad(lambda m:m["private_connectivity"].update(private_dns_resolution_tested=False))
    def test_database_delegation(self):self.bad(lambda m:m["private_connectivity"].update(database_subnet_delegated=False))
    def test_public_database(self):self.bad(lambda m:m["private_connectivity"].update(public_database_access_disabled=False))
    def test_endpoint_approval(self):self.bad(lambda m:m["private_connectivity"].update(private_endpoint_approved=False))
    def test_no_connectivity(self):self.bad(lambda m:m.pop("private_connectivity"))
    def test_flow_logs(self):self.bad(lambda m:m["audit"].update(flow_logs_enabled=False))
    def test_network_watcher(self):self.bad(lambda m:m["audit"].update(network_watcher_enabled=False))
    def test_security_review(self):self.bad(lambda m:m["audit"].update(security_reviewed=False))
    def test_dbre_probe(self):self.bad(lambda m:m["audit"].update(dbre_connectivity_tested=False))
    def test_no_audit(self):self.bad(lambda m:m.pop("audit"))
    def test_tag_environment(self):self.bad(lambda m:m["tags"].update(Environment="dev"))
    def test_tag_owner(self):self.bad(lambda m:m["tags"].update(Owner=""))
    def test_tag_managedby(self):self.bad(lambda m:m["tags"].update(ManagedBy="manual"))
    def test_no_tags(self):self.bad(lambda m:m.pop("tags"))
    def test_delete(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["delete"]))
    def test_replace(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["create","delete"]))
    def test_bad_action(self):self.bad_plan(lambda p:p["resource_changes"][0]["change"].update(actions=["destroy"]))
    def test_resource_type(self):self.bad_plan(lambda p:p["resource_changes"][0].update(type="azurerm_virtual_network"))
    def test_missing_plan(self):self.assertTrue(validate(SAFE,{},POLICY))
    def test_invalid_manifest(self):self.assertTrue(validate([],PLAN,POLICY))
    def test_fail_open_policy(self):
        p=copy.deepcopy(POLICY);p["deny_destructive_actions"]=False;self.assertTrue(validate(SAFE,PLAN,p))
    def test_noop_allowed(self):
        p=copy.deepcopy(PLAN);p["resource_changes"][0]["change"]["actions"]=["no-op"];self.assertEqual(validate(SAFE,p,POLICY),[])
if __name__=="__main__":unittest.main()
