import json,unittest
from contextlib import redirect_stdout
from io import StringIO
from failover_lab import FailoverError,region,lease,write_allowed,elect,recovery,dependencies,reconcile,chaos,demo,main
class Tests(unittest.TestCase):
    def bad(self,f):
        with self.assertRaises(FailoverError):f()
    def primary(self):return region("us-east-1",True,0,5,10)
    def standby(self):return region("us-west-2",True,10,20,35)
    def rec(self,*args):return recovery(*(args or (self.primary(),self.standby(),60,60,True,True,True,True)))
    def test_region(self):self.assertTrue(self.primary()["healthy"])
    def test_region_bad(self):self.bad(lambda:region("moon",True,0,1,1))
    def test_region_negative(self):self.bad(lambda:region("us-east-1",True,-1,1,1))
    def test_region_bool(self):self.bad(lambda:region("us-east-1",True,True,1,1))
    def test_lease(self):self.assertEqual(lease("primary",3,200,100)["epoch"],3)
    def test_lease_expired(self):self.bad(lambda:lease("primary",3,100,100))
    def test_lease_epoch(self):self.bad(lambda:lease("primary",0,200,100))
    def test_writer_allowed(self):self.assertTrue(write_allowed(lease("primary",3,200,100),"primary",3,120))
    def test_writer_stale_epoch(self):self.assertFalse(write_allowed(lease("primary",4,200,100),"primary",3,120))
    def test_writer_wrong_holder(self):self.assertFalse(write_allowed(lease("primary",3,200,100),"secondary",3,120))
    def test_writer_expired(self):self.assertFalse(write_allowed(lease("primary",3,200,100),"primary",3,200))
    def test_election(self):self.assertEqual(elect(["a","b"],{"a":1,"b":2},2),"b")
    def test_no_quorum(self):self.assertIsNone(elect(["a","b"],{"a":1,"b":1},2))
    def test_election_tie(self):self.assertEqual(elect(["b","a"],{"a":2,"b":2},2),"a")
    def test_election_bad(self):self.bad(lambda:elect(["a","a"],{"a":2},2))
    def test_recovery_ready(self):self.assertEqual(self.rec()["decision"],"advisory-ready")
    def test_same_region(self):self.assertIn("same_region",self.rec(self.primary(),self.primary(),60,60,True,True,True,True)["blockers"])
    def test_target_down(self):self.assertIn("target_unhealthy",self.rec(self.primary(),region("us-west-2",False,10,20,35),60,60,True,True,True,True)["blockers"])
    def test_rpo(self):self.assertIn("rpo_exceeded",self.rec(self.primary(),region("us-west-2",True,90,20,35),60,60,True,True,True,True)["blockers"])
    def test_rto(self):self.assertIn("rto_exceeded",self.rec(self.primary(),self.standby(),60,30,True,True,True,True)["blockers"])
    def test_fence(self):self.assertIn("old_writer_not_fenced",self.rec(self.primary(),self.standby(),60,60,False,True,True,True)["blockers"])
    def test_quorum(self):self.assertIn("quorum_missing",self.rec(self.primary(),self.standby(),60,60,True,False,True,True)["blockers"])
    def test_approval(self):self.assertIn("approval_missing",self.rec(self.primary(),self.standby(),60,60,True,True,False,True)["blockers"])
    def test_verification(self):self.assertIn("data_not_verified",self.rec(self.primary(),self.standby(),60,60,True,True,True,False)["blockers"])
    def test_no_real_failover(self):self.assertEqual(self.rec()["actual_failovers"],0)
    def test_dependencies(self):self.assertEqual(dependencies({"a":[],"b":["a"]}),["a","b"])
    def test_dag_missing(self):self.bad(lambda:dependencies({"b":["a"]}))
    def test_dag_cycle(self):self.bad(lambda:dependencies({"a":["b"],"b":["a"]}))
    def test_dag_empty(self):self.bad(lambda:dependencies({}))
    def test_reconcile_clean(self):self.assertEqual(reconcile({"a":1},{"a":1})["mismatched"],[])
    def test_reconcile_missing(self):self.assertEqual(reconcile({"a":1},{})["missing"],["a"])
    def test_reconcile_extra(self):self.assertEqual(reconcile({},{"a":1})["extra"],["a"])
    def test_reconcile_mismatch(self):self.assertEqual(reconcile({"a":1},{"a":2})["mismatched"],["a"])
    def test_chaos(self):self.assertEqual(chaos(["partition"])["production_actions"],0)
    def test_chaos_bad(self):self.bad(lambda:chaos(["delete_cluster"]))
    def test_demo(self):self.assertEqual(demo()["recovery"]["decision"],"advisory-ready")
    def test_failure(self):self.assertEqual(demo(True)["recovery"]["decision"],"hold")
    def test_no_network(self):self.assertEqual(demo()["network_calls"],0)
    def test_no_mutation(self):self.assertEqual(demo()["production_changes"],0)
    def test_fingerprint(self):self.assertNotEqual(demo()["fingerprint"],demo(True)["fingerprint"])
    def test_cli(self):
        out=StringIO()
        with redirect_stdout(out):self.assertEqual(main(["--dry-run"]),0)
        self.assertEqual(json.loads(out.getvalue())["mode"],"offline")
if __name__=="__main__":unittest.main()
