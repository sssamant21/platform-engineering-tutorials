import json,math,unittest
from contextlib import redirect_stdout
from io import StringIO
from capacity_lab import CapacityError,forecast,cpu_cores,replicas,storage,iops,pool,cost,loadtest,gate,demo,main
class Tests(unittest.TestCase):
    def bad(self,f):
        with self.assertRaises(CapacityError):f()
    def test_forecast(self):self.assertGreater(forecast(100,.01,30)["projected"],100)
    def test_forecast_headroom(self):self.assertGreater(forecast(100,0,0)["provisioned"],100)
    def test_forecast_zero(self):self.assertEqual(forecast(0,0,30)["projected"],0)
    def test_forecast_bad(self):self.bad(lambda:forecast(100,-1,30))
    def test_forecast_nan(self):self.bad(lambda:forecast(math.nan,.1,30))
    def test_forecast_full(self):self.bad(lambda:forecast(100,.1,30,1))
    def test_cpu(self):self.assertEqual(cpu_cores(1000,1,1),1)
    def test_cpu_headroom(self):self.assertGreater(cpu_cores(1000,1,.5),1)
    def test_cpu_bad(self):self.bad(lambda:cpu_cores(10,2,0))
    def test_cpu_bool(self):self.bad(lambda:cpu_cores(True,2))
    def test_replicas(self):self.assertEqual(replicas(100,40)["desired"],3)
    def test_replicas_min(self):self.assertEqual(replicas(0,40)["desired"],2)
    def test_replicas_cap(self):self.assertTrue(replicas(1000,40,2,8)["saturated"])
    def test_replicas_bad(self):self.bad(lambda:replicas(10,0))
    def test_replicas_bounds(self):self.bad(lambda:replicas(10,5,8,2))
    def test_storage(self):self.assertGreater(storage(20,30,1)["provisioned_gb"],storage(20,30,1)["used_gb"])
    def test_storage_zero(self):self.assertEqual(storage(0,30,1)["used_gb"],0)
    def test_storage_bad(self):self.bad(lambda:storage(20,30,1,0))
    def test_iops_safe(self):self.assertTrue(iops(100,2,1000)["safe"])
    def test_iops_overload(self):self.assertFalse(iops(1000,2,1000)["safe"])
    def test_iops_zero_limit(self):self.bad(lambda:iops(10,2,0))
    def test_pool_safe(self):self.assertTrue(pool(3,10,100,10)["safe"])
    def test_pool_unsafe(self):self.assertFalse(pool(10,20,100,10)["safe"])
    def test_pool_reserved(self):self.bad(lambda:pool(3,10,100,100))
    def test_cost(self):self.assertEqual(cost([{"team":"ops","units":2,"hours":10,"usd_per_unit_hour":1}])["total_usd"],20)
    def test_cost_attribution(self):self.assertEqual(len(cost([{"team":"a","units":1,"hours":1,"usd_per_unit_hour":1},{"team":"b","units":1,"hours":1,"usd_per_unit_hour":2}])["by_team_usd"]),2)
    def test_cost_empty(self):self.bad(lambda:cost([]))
    def test_cost_negative(self):self.bad(lambda:cost([{"team":"ops","units":-1,"hours":10,"usd_per_unit_hour":1}]))
    def test_load_pass(self):self.assertTrue(loadtest([20,30],0,1000,100)["pass"])
    def test_load_latency(self):self.assertFalse(loadtest([20,300],0,1000,100)["pass"])
    def test_load_errors(self):self.assertFalse(loadtest([20,30],10,1000,100)["pass"])
    def test_load_empty(self):self.bad(lambda:loadtest([],0,1000,100))
    def test_load_zero_requests(self):self.bad(lambda:loadtest([10],0,0,100))
    def test_load_invalid_errors(self):self.bad(lambda:loadtest([10],2,1,100))
    def test_gate_ready(self):self.assertEqual(gate(True,True,True,True,True,True)["decision"],"advisory-ready")
    def test_gate_cpu(self):self.assertIn("cpu",gate(False,True,True,True,True,True)["blockers"])
    def test_gate_iops(self):self.assertIn("iops",gate(True,False,True,True,True,True)["blockers"])
    def test_gate_pool(self):self.assertIn("connections",gate(True,True,False,True,True,True)["blockers"])
    def test_gate_slo(self):self.assertIn("slo",gate(True,True,True,False,True,True)["blockers"])
    def test_gate_budget(self):self.assertIn("budget",gate(True,True,True,True,False,True)["blockers"])
    def test_gate_approval(self):self.assertIn("approval",gate(True,True,True,True,True,False)["blockers"])
    def test_gate_bad(self):self.bad(lambda:gate(1,True,True,True,True,True))
    def test_demo(self):self.assertEqual(demo()["gate"]["decision"],"advisory-ready")
    def test_overload(self):self.assertEqual(demo(True)["gate"]["decision"],"hold")
    def test_no_network(self):self.assertEqual(demo()["network_calls"],0)
    def test_no_changes(self):self.assertEqual(demo()["production_changes"],0)
    def test_fingerprint(self):self.assertNotEqual(demo()["fingerprint"],demo(True)["fingerprint"])
    def test_cli(self):
        out=StringIO()
        with redirect_stdout(out):self.assertEqual(main(["--dry-run"]),0)
        self.assertEqual(json.loads(out.getvalue())["mode"],"offline")
if __name__=="__main__":unittest.main()
