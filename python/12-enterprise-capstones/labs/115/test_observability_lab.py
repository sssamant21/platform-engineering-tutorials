import json,math,unittest
from io import StringIO
from contextlib import redirect_stdout
from observability_lab import EvidenceError,percentile,redact,validate_trace,sli,burn,multiwindow,red,use,correlate,gate,demo,main
class Tests(unittest.TestCase):
    def bad(self,fn):
        with self.assertRaises(EvidenceError):fn()
    def span(self,ident="root_001",parent=None):return {"id":ident,"parent":parent,"service":"api","duration_ms":10,"status":"ok"}
    def test_p50(self):self.assertEqual(percentile([1,2,3],50),2)
    def test_p99(self):self.assertAlmostEqual(percentile([1,2,3],99),2.98)
    def test_empty(self):self.bad(lambda:percentile([],99))
    def test_nan(self):self.bad(lambda:percentile([math.nan],99))
    def test_negative(self):self.bad(lambda:percentile([-1],99))
    def test_bad_percentile(self):self.bad(lambda:percentile([1],101))
    def test_redact(self):self.assertEqual(redact({"api_key":"abc"})["api_key"],"[REDACTED]")
    def test_redact_patient(self):self.assertEqual(redact({"patient_id":"123"})["patient_id"],"[REDACTED]")
    def test_redact_safe(self):self.assertEqual(redact({"status":"ok"})["status"],"ok")
    def test_redact_invalid(self):self.bad(lambda:redact("x"))
    def test_trace(self):self.assertEqual(validate_trace([self.span()])["spans"],1)
    def test_trace_parent(self):self.assertEqual(validate_trace([self.span(),self.span("child_001","root_001")])["spans"],2)
    def test_trace_duplicate(self):self.bad(lambda:validate_trace([self.span(),self.span()]))
    def test_trace_orphan(self):self.bad(lambda:validate_trace([self.span("child_001","missing")]))
    def test_trace_two_roots(self):self.bad(lambda:validate_trace([self.span(),self.span("other_001")]))
    def test_trace_cycle(self):self.bad(lambda:validate_trace([self.span("one_001","two_001"),self.span("two_001","one_001")]))
    def test_trace_invalid_duration(self):self.bad(lambda:validate_trace([dict(self.span(),duration_ms=-1)]))
    def test_trace_error(self):self.assertEqual(validate_trace([dict(self.span(),status="error")])["errors"],1)
    def test_sli_pass(self):self.assertEqual(sli(1000,1000)["status"],"pass")
    def test_sli_breach(self):self.assertEqual(sli(900,1000)["status"],"breach")
    def test_sli_unknown(self):self.assertEqual(sli(0,0)["status"],"unknown")
    def test_sli_invalid(self):self.bad(lambda:sli(11,10))
    def test_sli_bool(self):self.bad(lambda:sli(True,1))
    def test_sli_budget(self):self.assertAlmostEqual(sli(999,1000)["remaining_events"],0,places=9)
    def test_burn(self):self.assertAlmostEqual(burn(1,1000),1)
    def test_burn_unknown(self):self.assertIsNone(burn(0,0))
    def test_burn_invalid(self):self.bad(lambda:burn(2,1))
    def test_multi_page(self):self.assertEqual(multiwindow(20,1000,40,2000)["status"],"page")
    def test_multi_observe(self):self.assertEqual(multiwindow(1,1000,1,1000)["status"],"observe")
    def test_multi_unknown(self):self.assertEqual(multiwindow(0,0,1,1000)["status"],"unknown")
    def test_red(self):self.assertEqual(red(2,1,[10,20])["error_ratio"],.5)
    def test_red_empty(self):self.assertIsNone(red(0,0,[])["p99_ms"])
    def test_red_bad(self):self.bad(lambda:red(2,1,[10]))
    def test_use(self):self.assertEqual(use(.8,2,0)["utilization"],.8)
    def test_use_bad(self):self.bad(lambda:use(1.1,0,0))
    def test_correlation(self):
        x=[{"incident":"inc_001","service":"api","kind":"metric","severity":"critical"}]
        self.assertEqual(correlate(x)["inc_001"]["critical"],1)
    def test_correlation_invalid(self):self.bad(lambda:correlate([{"incident":"x"}]))
    def test_gate_ready(self):self.assertEqual(gate("pass",1,True,True,True)["decision"],"advisory-ready")
    def test_gate_slo(self):self.assertIn("slo_breach",gate("breach",1,True,True,True)["blockers"])
    def test_gate_unknown(self):self.assertIn("slo_unknown",gate("unknown",1,True,True,True)["blockers"])
    def test_gate_coverage(self):self.assertIn("trace_coverage",gate("pass",.5,True,True,True)["blockers"])
    def test_gate_rollback(self):self.assertIn("rollback_missing",gate("pass",1,False,True,True)["blockers"])
    def test_gate_owner(self):self.assertIn("owner_missing",gate("pass",1,True,False,True)["blockers"])
    def test_gate_approval(self):self.assertIn("approval_missing",gate("pass",1,True,True,False)["blockers"])
    def test_demo(self):self.assertEqual(demo()["gate"]["decision"],"advisory-ready")
    def test_partial(self):self.assertEqual(demo(True)["gate"]["decision"],"hold")
    def test_no_network(self):self.assertEqual(demo()["network_calls"],0)
    def test_no_prod(self):self.assertEqual(demo()["production_mutations"],0)
    def test_fingerprint(self):self.assertNotEqual(demo()["fingerprint"],demo(True)["fingerprint"])
    def test_cli(self):
        out=StringIO()
        with redirect_stdout(out):self.assertEqual(main(["--dry-run"]),0)
        self.assertEqual(json.loads(out.getvalue())["mode"],"offline")
if __name__=="__main__":unittest.main()
