import unittest,json,math
from io import StringIO
from contextlib import redirect_stdout
from dataclasses import replace
from enterprise_lab import ArchitectureError,Dependency,topology,capacity,admission,percentile,slo,policy,failure,demo,main
class Tests(unittest.TestCase):
    def reject(self,fn):
        with self.assertRaises(ArchitectureError):fn()
    def edge(self):return Dependency("api","postgres",500,5,1)
    def test_edge(self):self.edge().validate()
    def test_bad_edge(self):self.reject(lambda:replace(self.edge(),target="unknown").validate())
    def test_timeout(self):self.reject(lambda:replace(self.edge(),timeout_ms=0).validate())
    def test_inflight(self):self.reject(lambda:replace(self.edge(),max_inflight=0).validate())
    def test_retry(self):self.reject(lambda:replace(self.edge(),retries=4).validate())
    def test_topology(self):self.assertEqual(topology([self.edge()])["count"],1)
    def test_topology_duplicate(self):self.reject(lambda:topology([self.edge(),self.edge()]))
    def test_topology_type(self):self.reject(lambda:topology([{}]))
    def test_topology_digest(self):self.assertEqual(topology([self.edge()])["fingerprint"],topology([self.edge()])["fingerprint"])
    def test_topology_digest_change(self):self.assertNotEqual(topology([self.edge()])["fingerprint"],topology([replace(self.edge(),timeout_ms=1000)])["fingerprint"])
    def test_capacity_safe(self):self.assertTrue(capacity(4,20,100,10)["safe"])
    def test_capacity_unsafe(self):self.assertFalse(capacity(5,30,100,10)["safe"])
    def test_capacity_reserved(self):self.assertEqual(capacity(2,10,100,20)["available_connections"],80)
    def test_capacity_bad(self):self.reject(lambda:capacity(0,10,100))
    def test_capacity_reserved_bad(self):self.reject(lambda:capacity(1,10,10,10))
    def test_admission(self):self.assertEqual(admission(20,5,3)["rejected"],12)
    def test_admission_no_reject(self):self.assertEqual(admission(3,5,3)["rejected"],0)
    def test_admission_bad(self):self.reject(lambda:admission(10,0,1))
    def test_p50(self):self.assertEqual(percentile([1,2,3],50),2)
    def test_p95(self):self.assertAlmostEqual(percentile([0,100],95),95)
    def test_p99(self):self.assertAlmostEqual(percentile([0,100],99),99)
    def test_percentile_nan(self):self.reject(lambda:percentile([math.nan],50))
    def test_percentile_empty(self):self.reject(lambda:percentile([],50))
    def test_percentile_bad(self):self.reject(lambda:percentile([1],101))
    def test_slo_pass(self):self.assertEqual(slo(1000,1000)["status"],"pass")
    def test_slo_breach(self):self.assertEqual(slo(900,1000)["status"],"breached")
    def test_slo_unknown(self):self.assertEqual(slo(0,0)["status"],"unknown")
    def test_slo_bad(self):self.reject(lambda:slo(101,100))
    def test_policy_allow(self):self.assertEqual(policy("operator","deploy",30,True,True)["decision"],"advisory-ready")
    def test_policy_rbac(self):self.assertIn("rbac",policy("reader","deploy",30,True,True)["blockers"])
    def test_policy_secret(self):self.assertIn("secret-rotation",policy("operator","deploy",90,True,True)["blockers"])
    def test_policy_trace(self):self.assertIn("trace-coverage",policy("operator","deploy",30,False,True)["blockers"])
    def test_policy_rollback(self):self.assertIn("rollback",policy("operator","deploy",30,True,False)["blockers"])
    def test_policy_bad(self):self.reject(lambda:policy("guest","read",0,True,True))
    def test_policy_no_mutation(self):self.assertEqual(policy("operator","deploy",30,True,True)["mutations"],0)
    def test_failure(self):self.assertEqual(failure("postgres","saturation")["faults_injected"],0)
    def test_failure_bad(self):self.reject(lambda:failure("unknown","timeout"))
    def test_failure_network(self):self.assertEqual(failure("kafka","lag")["network_calls"],0)
    def test_demo(self):self.assertEqual(demo()["mode"],"offline")
    def test_demo_partial(self):self.assertEqual(demo(True)["policy"]["decision"],"hold")
    def test_demo_no_network(self):self.assertEqual(demo()["network_calls"],0)
    def test_demo_no_mutation(self):self.assertEqual(demo()["mutations"],0)
    def test_cli(self):
        out=StringIO()
        with redirect_stdout(out):self.assertEqual(main(["--dry-run"]),0)
        self.assertEqual(json.loads(out.getvalue())["topology"]["count"],4)
    def test_cli_partial(self):
        out=StringIO()
        with redirect_stdout(out):main(["--partial"])
        self.assertEqual(json.loads(out.getvalue())["policy"]["decision"],"hold")
if __name__=="__main__":unittest.main()
