import json,unittest
from io import StringIO
from contextlib import redirect_stdout
from readiness_lab import ReadinessError,Evidence,WEIGHTS,review,slo,load_gate,chaos_plan,incident,sample,main
class Tests(unittest.TestCase):
    def bad(self,fn):
        with self.assertRaises(ReadinessError):fn()
    def evidence(self):return [Evidence(k,True,"platform_team",f"evidence/{k}/20261019","2026-10-19T20:00:00Z") for k in WEIGHTS]
    def test_weights(self):self.assertEqual(sum(WEIGHTS.values()),100)
    def test_evidence(self):self.assertEqual(self.evidence()[0].owner,"platform_team")
    def test_invalid_owner(self):self.bad(lambda:Evidence("security",True,"!","evidence/security/20261019","2026-10-19T20:00:00Z"))
    def test_invalid_control(self):self.bad(lambda:Evidence("magic",True,"platform_team","evidence/magic/20261019","2026-10-19T20:00:00Z"))
    def test_invalid_timestamp(self):self.bad(lambda:Evidence("security",True,"platform_team","evidence/security/20261019","today"))
    def test_ready(self):self.assertEqual(review(self.evidence(),True,True)["decision"],"advisory-ready")
    def test_score(self):self.assertEqual(review(self.evidence(),True,True)["score"],100)
    def test_missing(self):self.assertIn("operations",review(self.evidence()[:-1],True,True)["missing"])
    def test_critical_failed(self):
        items=self.evidence();items[4]=Evidence("security",False,"platform_team","evidence/security/20261019","2026-10-19T20:00:00Z")
        self.assertIn("failed:security",review(items,True,True)["blockers"])
    def test_noncritical_failed(self):
        items=self.evidence();items[0]=Evidence("architecture",False,"platform_team","evidence/architecture/20261019","2026-10-19T20:00:00Z")
        self.assertIn("score_below_90",review(items,True,True)["blockers"])
    def test_duplicate(self):self.bad(lambda:review(self.evidence()+[self.evidence()[0]],True,True))
    def test_no_approval(self):self.assertIn("approval_missing",review(self.evidence(),False,True)["blockers"])
    def test_no_rollback(self):self.assertIn("rollback_not_tested",review(self.evidence(),True,False)["blockers"])
    def test_no_prod(self):self.assertEqual(review(self.evidence(),True,True)["production_actions"],0)
    def test_slo_pass(self):self.assertEqual(slo(9999,10000,.999,1,1000,2,2000)["status"],"pass")
    def test_slo_breach(self):self.assertEqual(slo(9900,10000,.999,1,1000,2,2000)["status"],"breach")
    def test_slo_unknown(self):self.assertEqual(slo(0,0,.999,0,0,0,0)["status"],"unknown")
    def test_slo_budget(self):self.assertGreater(slo(9999,10000,.999,1,1000,2,2000)["remaining_budget"],0)
    def test_slo_burn(self):self.assertGreater(slo(9999,10000,.999,20,1000,2,2000)["fast_burn"],10)
    def test_slo_invalid(self):self.bad(lambda:slo(100,10,.999,1,100,1,100))
    def test_slo_target(self):self.bad(lambda:slo(10,10,1,0,10,0,10))
    def test_load_pass(self):self.assertEqual(load_gate(80,150,0,.001,.5,.6,.6)["decision"],"pass")
    def test_load_p99(self):self.assertIn("latency",load_gate(200,150,0,.001,.5,.6,.6)["failed"])
    def test_load_error(self):self.assertIn("errors",load_gate(80,150,.1,.001,.5,.6,.6)["failed"])
    def test_load_cpu(self):self.assertIn("cpu",load_gate(80,150,0,.001,.8,.6,.6)["failed"])
    def test_load_memory(self):self.assertIn("memory",load_gate(80,150,0,.001,.5,.9,.6)["failed"])
    def test_load_pool(self):self.assertIn("db_pool",load_gate(80,150,0,.001,.5,.6,.9)["failed"])
    def test_load_bad(self):self.bad(lambda:load_gate(80,150,0,.001,1.2,.6,.6))
    def test_chaos_ready(self):self.assertEqual(chaos_plan("pod_kill","staging",1,True,True)["decision"],"plan-ready")
    def test_chaos_radius(self):self.assertIn("blast_radius_exceeded",chaos_plan("pod_kill","staging",3,True,True)["blockers"])
    def test_chaos_abort(self):self.assertIn("abort_guard_missing",chaos_plan("pod_kill","staging",1,False,True)["blockers"])
    def test_chaos_approval(self):self.assertIn("owner_approval_missing",chaos_plan("pod_kill","staging",1,True,False)["blockers"])
    def test_chaos_bad_fault(self):self.bad(lambda:chaos_plan("destroy_prod","staging",1,True,True))
    def test_chaos_bad_env(self):self.bad(lambda:chaos_plan("pod_kill","prod",1,True,True))
    def test_chaos_no_injection(self):self.assertEqual(chaos_plan("pod_kill","staging",1,True,True)["faults_injected"],0)
    def test_incident(self):self.assertEqual(incident("SEV1",["api_5xx"],"platform_team",True)["action"],"escalate_and_contain")
    def test_incident_signals(self):self.assertEqual(incident("SEV2",["p99","p99"],"platform_team",True)["signals"],["p99"])
    def test_incident_bad(self):self.bad(lambda:incident("SEV0",["p99"],"platform_team",True))
    def test_incident_no_prod(self):self.assertEqual(incident("SEV2",["p99"],"platform_team",True)["production_actions"],0)
    def test_sample_ready(self):self.assertEqual(sample()["review"]["decision"],"advisory-ready")
    def test_sample_failure(self):self.assertEqual(sample(True)["review"]["decision"],"hold")
    def test_sample_no_network(self):self.assertEqual(sample()["network_calls"],0)
    def test_sample_no_prod(self):self.assertEqual(sample()["production_actions"],0)
    def test_fingerprint(self):self.assertNotEqual(sample()["fingerprint"],sample(True)["fingerprint"])
    def test_cli(self):
        out=StringIO()
        with redirect_stdout(out):self.assertEqual(main(["--dry-run"]),0)
        self.assertEqual(json.loads(out.getvalue())["mode"],"offline")
if __name__=="__main__":unittest.main()
