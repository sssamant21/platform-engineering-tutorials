import json,unittest
from contextlib import redirect_stdout
from io import StringIO
from security_dr_lab import PolicyError,principal,allowed,secret,restore,supply,controls,redact,demo,main
class Tests(unittest.TestCase):
    def bad(self,fn):
        with self.assertRaises(PolicyError):fn()
    def user(self):return principal("worker_001","tenant_001",["reader","operator"],1000,100)
    def test_principal(self):self.assertEqual(self.user()["tenant"],"tenant_001")
    def test_bad_subject(self):self.bad(lambda:principal("!","tenant_001",["reader"],1000,100))
    def test_expired(self):self.bad(lambda:principal("worker_001","tenant_001",["reader"],100,100))
    def test_roles(self):self.bad(lambda:principal("worker_001","tenant_001",["root"],1000,100))
    def test_empty_roles(self):self.bad(lambda:principal("worker_001","tenant_001",[],1000,100))
    def test_read(self):self.assertTrue(allowed(self.user(),"tenant_001","read"))
    def test_cross_tenant(self):self.assertFalse(allowed(self.user(),"tenant_002","read"))
    def test_operator(self):self.assertTrue(allowed(self.user(),"tenant_001","backup_plan"))
    def test_restore_denied(self):self.assertFalse(allowed(self.user(),"tenant_001","restore_propose"))
    def test_dr_admin(self):self.assertTrue(allowed(principal("admin_001","tenant_001",["dr_admin"],1000,100),"tenant_001","restore_propose"))
    def test_bad_action(self):self.bad(lambda:allowed(self.user(),"tenant_001","delete_all"))
    def test_secret_pass(self):self.assertEqual(secret(10,30,True),"pass")
    def test_secret_old(self):self.assertEqual(secret(30,30,True),"hold")
    def test_secret_unencrypted(self):self.assertEqual(secret(10,30,False),"hold")
    def test_secret_invalid(self):self.bad(lambda:secret(-1,30,True))
    def rec(self,*args):return restore(*(args or (20,60,80,120,True,True,True,True,True)))
    def test_restore_ready(self):self.assertEqual(self.rec()["decision"],"advisory-ready")
    def test_rpo(self):self.assertIn("rpo",self.rec(100,60,80,120,True,True,True,True,True)["blockers"])
    def test_rto(self):self.assertIn("rto",self.rec(20,60,130,120,True,True,True,True,True)["blockers"])
    def test_checksum(self):self.assertIn("checksum",self.rec(20,60,80,120,False,True,True,True,True)["blockers"])
    def test_encryption(self):self.assertIn("encryption",self.rec(20,60,80,120,True,False,True,True,True)["blockers"])
    def test_immutable(self):self.assertIn("immutability",self.rec(20,60,80,120,True,True,False,True,True)["blockers"])
    def test_drill(self):self.assertIn("drill",self.rec(20,60,80,120,True,True,True,False,True)["blockers"])
    def test_approval(self):self.assertIn("approval",self.rec(20,60,80,120,True,True,True,True,False)["blockers"])
    def test_restore_bad(self):self.bad(lambda:self.rec(-1,60,80,120,True,True,True,True,True))
    def test_no_restore(self):self.assertEqual(self.rec()["production_restores"],0)
    def test_supply_pass(self):self.assertEqual(supply("a"*64,True,True,0,True)["decision"],"advisory-ready")
    def test_supply_unsigned(self):self.assertEqual(supply("a"*64,False,True,0,True)["decision"],"hold")
    def test_supply_sbom(self):self.assertEqual(supply("a"*64,True,False,0,True)["decision"],"hold")
    def test_supply_critical(self):self.assertEqual(supply("a"*64,True,True,1,True)["decision"],"hold")
    def test_supply_approval(self):self.assertEqual(supply("a"*64,True,True,0,False)["decision"],"hold")
    def test_supply_digest(self):self.bad(lambda:supply("invalid",True,True,0,True))
    def test_controls_pass(self):self.assertEqual(controls({"iam":True})["status"],"pass")
    def test_controls_hold(self):self.assertEqual(controls({"iam":False})["failed"],["iam"])
    def test_controls_invalid(self):self.bad(lambda:controls({}))
    def test_redact(self):self.assertEqual(redact({"api_token":"x"})["api_token"],"[REDACTED]")
    def test_redact_patient(self):self.assertEqual(redact({"patient_id":"123"})["patient_id"],"[REDACTED]")
    def test_redact_safe(self):self.assertEqual(redact({"status":"ok"})["status"],"ok")
    def test_demo(self):self.assertEqual(demo()["recovery"]["decision"],"advisory-ready")
    def test_failure(self):self.assertEqual(demo(True)["recovery"]["decision"],"hold")
    def test_no_network(self):self.assertEqual(demo()["network_calls"],0)
    def test_no_writes(self):self.assertEqual(demo()["production_mutations"],0)
    def test_fingerprint(self):self.assertNotEqual(demo()["fingerprint"],demo(True)["fingerprint"])
    def test_cli(self):
        out=StringIO()
        with redirect_stdout(out):self.assertEqual(main(["--dry-run"]),0)
        self.assertEqual(json.loads(out.getvalue())["mode"],"offline")
if __name__=="__main__":unittest.main()
